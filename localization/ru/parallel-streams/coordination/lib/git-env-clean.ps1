#Requires -Version 7
<#
Копия ради автономности скилла: оригинал проекта живёт в `scripts/git-env-clean.ps1` и правится
там отдельно — эту копию руками не редактировать, только переносить правку из оригинала.

Снимает с окружения ТЕКУЩЕГО процесса git-переменные, которые перебивают выбор папки.

Подключать точкой ДО первого обращения к git — из хука, из общей части инструмента, откуда угодно.
Ничего не печатает, ничего не возвращает и никогда не бросает наружу.

Зачем это вообще нужно. Флаг -C выбирает папку, но НЕ перебивает GIT_DIR: заданный без
GIT_WORK_TREE, он уводит git к чужому служебному каталогу, а рабочим деревом объявляет текущую
папку. Отсюда сразу два перевёртыша, и оба тихие:

- «не репозиторий» перестаёт наступать когда-либо: любая посторонняя папка отвечает успехом и
  зовётся корнем — а поиск корня («где лежит объявление сборок», «где лежит доска») уводит в
  чужое дерево или в первую попавшуюся подпапку;
- рабочая копия проекта становится вечно «грязной»: весь состав чужого репозитория числится в ней
  удалённым, а имя ветки и список рабочих деревьев приходят от чужого репозитория целиком.

Откуда зараза. Такие переменные заводят по ходу работы с рабочими деревьями, рассчитывая, что они
переживут переход в другую папку, а хуки и скрипты наследуют окружение долгоживущего процесса
сессии. В чистом процессе — в тестах и на сборочном боксе — этого не видно НИКОГДА, поэтому беда
выглядит как «зелено везде, ломается только вживую».

Восстанавливать нечего: и хук, и разовый запуск скрипта живут одну команду и умирают вместе с ней.
Долгоживущей оболочке файл ничего не ломает тоже — переменные снимаются в её собственном процессе,
а нужны они были бы там ровно для того, от чего мы и защищаемся.

‼️ Стираем ПО-НАСТОЯЩЕМУ, а не обнуляем. Переменная, оставшаяся заданной, но ПУСТОЙ, — это хуже
исходной беды: пустой служебный каталог git считает явно указанным и отвечает «not a git
repository: ''» уже в любой папке, то есть состояние дерева не выясняется нигде. Замерено на
оболочке 7.6.5: пустой переменная остаётся и от присвоения пустой строки, и от вызова метода .NET
с $null — в строковом параметре $null сам обращается в пустую строку, и «обнулить методом»
приводит ровно в эту ловушку. Присвоение $null через $env: семёрка как раз считает удалением и оно
бы годилось, но от ловушки отличается на один символ. Remove-Item взят потому, что намерение в нём
написано словом и перепутать его не с чем.
#>

foreach ($name in @(
        'GIT_DIR',
        'GIT_WORK_TREE',
        'GIT_CEILING_DIRECTORIES',
        'GIT_INDEX_FILE',
        'GIT_COMMON_DIR',
        'GIT_OBJECT_DIRECTORY',
        'GIT_ALTERNATE_OBJECT_DIRECTORIES')) {
    Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
}
