<#
Копия ради автономности скилла: оригинал проекта живёт в `scripts/hooks/hook-io.ps1` и правится
там отдельно — эту копию руками не редактировать, только переносить правку из оригинала.

Общее чтение вызова, который среда подаёт хуку в стандартный ввод.

Подаётся он всегда в UTF-8, а [Console]::In декодирует поток кодовой страницей КОНСОЛИ той
оболочки, из которой запущена команда. У bash-оболочки помощника это cp866: кириллица в пути и в
самой команде превращается в мусор. Дальше хук судит по подменённым данным — папка вызова не
находится, образец замены не опознаётся — и молчит об этом, потому что все хуки глушат любую
неожиданность и выходят нулём. Расхождение при этом выглядит как разница между оболочками: один и
тот же хук на одном и том же дереве решает по-разному.

Поэтому поток читаем напрямую и декодируем UTF-8 сами. Кодовую страницу консоли не трогаем: консоль
общая с родительской оболочкой, и смена страницы из хука меняет её и там.
#>

function Read-HookInput {
    $reader = [System.IO.StreamReader]::new(
        [Console]::OpenStandardInput(),
        [System.Text.UTF8Encoding]::new($false)
    )
    return $reader.ReadToEnd()
}
