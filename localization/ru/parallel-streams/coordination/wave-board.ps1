    'Claim' {
        # Объявление потока. Первое действие вкладки после того, как заведено рабочее дерево: без
        # него поток снаружи неотличим от «ещё не открывали», а находки ему адресуют по имени
        # ветки, которое к этому моменту уже другое.
        #
        # ‼️ Корень дерева спрашиваем ПЕРВЫМ делом и строго: под этим ключом ляжет заявка, и под ним
        # же её будет искать сдача. Молчаливый откат на текущую папку сменил бы вкладке личность —
        # объявились бы одним ключом, а сдавались другим, и сдача ответила бы «сдавать нечего» кодом
        # успеха. Лучше отказать вслух до записи, чем завести заявку, которую никто не найдёт.
        $tree = Get-TreeRoot -Strict
        $branch = ''
        try {
            $head = (& git rev-parse --abbrev-ref HEAD 2>$null)
            if ($LASTEXITCODE -eq 0 -and $head) { $branch = $head.Trim() }
        } catch {
            # Открепление от ветки: заявке хватит пути рабочего дерева.
        }
        # ‼️ Отсюда и до конца разрешения спора — под замком реестра заявок. Выбор номера идёт по
        # снимку реестра, и без замка вкладки, открытые разом, читают ОДИН И ТОТ ЖЕ снимок: номер у
        # всех выходит одинаковый, а круг разрешения спора ниже добивает не всё — из него выходят по
        # снимку, устаревшему на чужой сдвиг, и два потока остаются с одним адресом молча, с бодрым
        # рапортом каждый. Разбор сценария целиком — у `Enter-RegistryLock`.
        #
        # Замок снимается и при отказе внутри: `finally` в PowerShell отрабатывает и на `exit`
        # (`Deny-Call`), и на исключении, перехваченном ловушкой выше. А если вкладку убьют, не дав
        # отработать и ему, замок отпустит система: держит его открытый дескриптор, а не файл.
        $lockHandle = Enter-RegistryLock -Dir $registry
        try {
            # ‼️ Строго: этот снимок ВЫБИРАЕТ НОМЕР потока. Не увидеть соседа тут — значит выдать
            # его номер второй раз, молча и навсегда; лучше отказать вслух и попросить повторить.
            $claims = @(Get-Claims -Dir $registry -Strict)
            # Куда ляжет заявка и что в этой папке лежало до неё. Обе величины одни и те же для
            # всего блока, и спрашиваются они ПЕРВЫМИ: по ним берётся адрес потока при коротком
            # объявлении и по ним же решается, не затрёт ли объявление чужой поток.
            #
            # ‼️ Каноничный ключ — корень рабочего дерева, но заявки, поданные ПРЕЖНЕЙ версией из
            # подкаталога дерева, лежат под ключом того подкаталога. Не найдя своего файла по
            # каноничному имени, ищем свою запись второй дорогой — той же, какой уже пользуются
            # сдача и сторож доставки: по ТОЧНОМУ совпадению записанной в заявке рабочей папки.
            # Пишем потом обратно в НАЙДЕННЫЙ файл: ни один файл не заводится, не удаляется и не
            # переименовывается.
            #
            # ‼️ Без этой дороги объявление тем же адресом заводило ВТОРУЮ открытую запись того же
            # потока: инструмент печатал вкладке предупреждение, что она спорит сама с собой, и всё
            # равно писал вторую запись кодом успеха. Адрес после этого вели две записи, и кому
            # придёт находка, решала опись каталога.
            #
            # Совпадение только ТОЧНОЕ — ни «начинается с», ни «лежит внутри»: иначе вкладка
            # забрала бы заявку соседнего дерева, вложенного в её папку.
            #
            # ‼️ Выбор ОДИН на все три решения: правило папки, наследование и запись файла обязаны
            # смотреть в одну и ту же запись. Прежде их было два — правило папки брало ПЕРВУЮ по
            # порядку описи запись этой папки, а запись файла шла в найденную по каноничному ключу,
            # — и на папке, где рядом лежат сданная и открытая записи, они расходились: правило
            # смотрело на сданную (та в счёт не идёт и отказ не поднимает), а писали поверх ЖИВОЙ.
            # Короткое объявление другого потока проходило кодом успеха и стирало работающий.
            #
            # ‼️ Незакрытая всегда старше сданной. Двух незакрытых на одну папку не бывает по
            # правилу реестра; раз уж случилось — выбирать за человека нельзя, объявление отказывает
            # вслух ровно так же, как отказывает сдача.
            $claimPath = Get-ClaimPath -Dir $registry -TreePath $tree
            $hereKeys = @(@($tree, $PWD.Path) | ForEach-Object { Get-FolderKey -Path $_ } |
                    Where-Object { $_ } | Select-Object -Unique)
            $canonKey = Get-FolderKey -Path $claimPath
            $mineHere = @($claims | Where-Object {
                    (Get-FolderKey -Path $_.Record.worktree) -in $hereKeys -or
                    (Get-FolderKey -Path $_.File) -eq $canonKey
                })
            # Закрытость — ЕДИНЫМ признаком: перенесённая запись в своём файле выглядит открытой, и,
            # читай мы поле напрямую, вкладка, у которой адрес забрали, считала бы её своей живой
            # заявкой и продолжала бы по ней поток, которого у неё уже нет.
            $openHere = @($mineHere | Where-Object { -not $_.Closed })
            if ($openHere.Count -gt 1) {
                $names = @($openHere | ForEach-Object { $_.File }) -join ', '
                Deny-Call "на эту рабочую папку в реестре сразу $($openHere.Count) незакрытых заявок ($names) — какую из них продолжает эта вкладка, механизм решать не вправе. Уберите лишнюю и повторите."
            }
            $previous = if ($openHere.Count -eq 1) {
                $openHere[0]
            } elseif ($mineHere.Count -eq 1) {
                $mineHere[0]
            } else {
                $null
            }
            # ‼️ Пишем в файл ВЫБРАННОЙ записи, а не в каноничный: иначе объявление завело бы вторую
            # запись того же потока рядом с найденной, и кому придёт находка, решала бы опись
            # каталога. Ни один файл при этом не заводится, не удаляется и не переименовывается.
            if ($previous) { $claimPath = $previous.File }

            # ‼️ Прежняя НЕЗАКРЫТАЯ заявка этой папки — это ТОТ ЖЕ поток, а не помеха. Отсюда она и
            # поднялась выше лестницы подстановки волны: ниже по ней берутся волна, номер и всё
            # остальное, чего вкладка в коротком объявлении не назвала. Сданная в счёт не идёт —
            # вкладки, которая вела тот поток, больше нет, и следующий поток в этой папке новый.
            $previousOpen = if ($previous -and -not $previous.Closed) {
                $previous
            } else {
                $null
            }
            # ‼️ Своя ПЕРЕНЕСЁННАЯ запись — тоже свой поток, просто оставшийся без адреса. Имя,
            # задачи и план у неё собственные, и вкладка, вернувшая себе адрес напечатанной
            # командой, обязана получить их обратно: иначе возврат отдаёт адрес, но теряет сам
            # поток — вкладка объявляется безымянной, а соседи видят пустую строку вместо работы.
            #
            # Сданная сюда НЕ попадает: вкладки, которая вела тот поток, больше нет, и следующий
            # поток в этой папке — другой. Наследовать у неё значило бы отзываться на её имя и
            # перехватывать адресованные ей находки.
            $previousSelf = if ($previousOpen) {
                $previousOpen
            } elseif ($previous -and $previous.Superseded) {
                $previous
            } else {
                $null
            }
            # Волну подставляем сами, если её не назвали: канал ставят и в проекты, где волн нет
            # вовсе, и там вкладке неоткуда взять ни номер волны, ни номер потока. Отказ на этом
            # месте был тупиком — объявиться нельзя, а без объявления поток снаружи не существует.
            #
            # Ступени сверху вниз: названная волна → волна из имени плана → СВОЯ ПРЕЖНЯЯ ЗАЯВКА →
            # идущая рядом работа → новая волна по сегодняшней дате.
            $waveAuto = $false
            $waveSource = 'named'
            # Что вкладка возьмёт у своей же прежней записи. Величины заведены здесь, до лестницы,
            # потому что лестница выбирает только ВОЛНУ, а наследование остальных полей идёт ниже —
            # когда адрес выбран целиком. Два признака рядом с полями: выдан ли номер сейчас или
            # унаследован (об этом говорят вслух по-разному) и несла ли прежняя запись признак
            # «волна подставлена сама» вообще — его отсутствие тоже наследуется.
            $streamInherited = $false
            $waveAutoKnown = $true
            $claimedAt = (Get-Date).ToString('s')
            $claimName = $StreamName
            $claimTasks = $Tasks
            $claimPlan = $Plan
            if ($Wave) {
                $waveKey = Get-WaveKey -Raw $Wave
            } elseif ($Plan) {
                $waveKey = Get-WaveKey -Raw $Plan
                $waveSource = 'plan'
            } elseif ($previousOpen -and $previousOpen.WaveKey) {
                # ‼️ Вкладка объявляется заново из своей же папки и волну не называет — это
                # ПРОДОЛЖЕНИЕ того же потока, а не новый. Без этой ступени поток уезжал в волну по
                # сегодняшней дате и терял вместе с адресом имя, задачи, план и старшинство: соседи
                # продолжали адресовать находки по прежнему адресу, а его в реестре уже не было.
                $waveKey = $previousOpen.WaveKey
                $waveSource = 'own'
            } else {
                $joined = Get-AutoWaveKey -Claims $claims
                if ($joined) {
                    $waveKey = $joined
                    $waveSource = 'joined'
                } else {
                    $waveKey = Get-DateWaveKey
                    $waveSource = 'date'
                }
                # ‼️ Признак нужен именно здесь: присоединяться можно ТОЛЬКО к волне, подставленной
                # самой. У названной волны номера потоков идут из плана, и занять там чужой номер
                # значит развести адресацию надвое. На ступени «своя прежняя заявка» он не ставится,
                # а НАСЛЕДУЕТСЯ: волна там могла быть и названной.
                $waveAuto = $true
            }
            if (-not $waveKey) {
                # Сюда попадаем, только если волну (или план) назвали, но имя свелось к пустому: без
                # имени волны у потока нет адреса, и находки ему не доставит никто.
                $named = if ($Wave) { $Wave } else { $Plan }
                Deny-Call "волна «$named» сводится к пустому имени — назовите её словом или номером"
            }
            # Номер потока тоже необязателен: в проекте без плана его неоткуда взять, а адресу он
            # нужен всегда. Названный номер работает как раньше — он идёт из таблицы плана.
            $streamAuto = $false
            if ($Stream) {
                $streamKey = Get-StreamNumberKey -Raw $Stream
                if (-not $streamKey) { Deny-Call "номер потока «$Stream» сводится к пустому — назовите его как в плане" }
            } elseif ($previousOpen -and $previousOpen.WaveKey -eq $waveKey -and $previousOpen.StreamKey) {
                # ‼️ Номер, взятый у своей прежней записи, остаётся ВЫДАННЫМ, а не названным: круг
                # уступки обязан работать ровно как сегодня. Считай мы его названным — повторно
                # объявившаяся вкладка перестала бы уступать старшему соседу и получила бы отказ с
                # единственным разрушительным выходом.
                #
                # ‼️ Условие тут — совпадение ВОЛНЫ, а не «волну не назвали». Вкладка вправе назвать
                # свою же волну словом и номера не называть; требуй мы молчания про волну, номер
                # пошёл бы в общий подбор, а вместе с ним уехали бы имя, задачи и старшинство.
                $streamKey = $previousOpen.StreamKey
                $streamAuto = $true
                $streamInherited = $true
            } else {
                $streamKey = Get-NextStreamNumber -Claims $claims -WaveKey $waveKey -TreePath $tree
                $streamAuto = $true
            }
            # ‼️ Ступень наследования: неназванные поля берутся у СВОЕЙ НЕЗАКРЫТОЙ заявки ТОГО ЖЕ
            # АДРЕСА. Каждое поле — только если его не назвали в вызове: назвали, значит вкладка
            # знает лучше, и наследование тут же затёрло бы названное.
            #
            # ‼️ Условие — совпадение адреса, а НЕ «волну не назвали». Пока ступень висела на
            # молчании про волну, частичное переобъявление («назвал волну, номер не назвал» или
            # «назвал путь плана») оставляло адрес прежним, но стирало имя, задачи и путь плана,
            # сбрасывало время объявления и вдобавок печатало неправду про свежевыданный номер.
            # Дороже всего терялось время объявления: с ним уходит старшинство в споре за номер, и
            # круг уступки отдаёт адрес соседу, объявившемуся позже, — поток молча уезжает на другой
            # номер. Продолжение потока не бывает частичным: продолжается он весь.
            $sameStream = (
                $previousSelf -and $previousSelf.WaveKey -eq $waveKey -and
                $previousSelf.StreamKey -eq $streamKey
            )
            if ($sameStream) {
                # Время объявления — это старшинство в споре за номер. Возьми мы текущее, и вкладка
                # уступала бы номер всякому, кто объявился между её двумя объявлениями.
                #
                # ‼️ Но у ПЕРЕНЕСЁННОЙ записи старшинство не наследуется: оно потеряно вместе с
                # самим адресом, и наследовать его нечего. Дело не только в честности — вкладка,
                # вернувшая себе адрес, выглядела бы объявившейся РАНЬШЕ, чем у неё его забрали:
                # ребро соперника снова начало бы действовать, обе записи погасили бы друг друга, и
                # ведущей у адреса не осталось бы ни одной.
                if (-not $previousSelf.Superseded) {
                    $inheritedAt = if ($previousSelf.Record.claimed_at -is [datetime]) {
                        # Чтение JSON превращает время в дату — возвращаем ему тот же вид, каким оно
                        # легло в заявку, иначе в файле оказалась бы запись системной локали.
                        $previousSelf.Record.claimed_at.ToString('s')
                    } else {
                        [string]$previousSelf.Record.claimed_at
                    }
                    if ($inheritedAt) { $claimedAt = $inheritedAt }
                }
                if (-not $claimName) { $claimName = [string]$previousSelf.Record.name }
                if (-not $claimTasks) { $claimTasks = [string]$previousSelf.Record.tasks }
                if (-not $claimPlan) { $claimPlan = [string]$previousSelf.Record.plan }
                if ($waveSource -eq 'own') {
                    # ‼️ Признак «волна подставлена сама» берётся КАК ЛЕЖАЛ — вместе с его
                    # отсутствием, — и только когда волну не называли. На нём висит вся развилка
                    # «Хвосты волны или ответ владельцу», а сверх неё право соседа присоединиться к
                    # этой волне. У заявки прежней версии поля нет вовсе, и все читатели судят такую
                    # заявку по имени волны; выдумай мы ей значение — волна, названная словом, вдруг
                    # стала бы «подставленной самой», и сосед занял бы в ней номер, объявленный в
                    # плане. Поэтому поля не было — не заводим и мы (ниже, при сборке записи).
                    #
                    # Волну назвали — признак честно становится «названа»: это ответ на ВЫЗОВ, а не
                    # свойство потока, и наследовать его вопреки сказанному значило бы врать.
                    $waveAutoKnown = Test-ClaimHasField -Claim $previousSelf.Record -Name 'wave_auto'
                    $waveAuto = [bool]$previousSelf.Record.wave_auto
                }
            }
            # ‼️ ДРУГОЙ поток из той же папки — отказ ДО записи. Заявка на папку ОДНА, поэтому
            # второе объявление стирало первую молча, а с ней и весь поток: его задачи выглядели
            # невзятыми, находки ему не адресовали, а его собственная сдача в конце закрывала уже
            # чужую запись. 31.08.2026 так бесследно исчез поток 9 волны 5 в соседнем проекте, и не
            # заметила этого ни одна сторона.
            #
            # ‼️ Отказ стоит ДО записи, а не предупреждением после: предупреждение после — это
            # ровно то, что сегодня не работает, потому что стирать уже нечего.
            #
            # Сверяем АДРЕС целиком — волну и номер: ими поток назван в плане и ими ему адресуют
            # находки. Совпал — это объявление того же потока заново (переименовали ветку,
            # перезапустили вкладку), и оно проходит как сегодня.
            #
            # Сданный поток не в счёт: вкладки, которая его вела, больше нет, и следующий поток в
            # той же папке — обычный порядок работы. Безадресная заявка (без волны или без номера)
            # тоже: адресовать такому потоку находку всё равно нечем, терять в ней нечего.
            #
            # ‼️ Ложного отказа не выйдет и там, где номер выдаёт сам инструмент: у незакрытой
            # заявки ЭТОЙ папки номер берётся ступенью наследования выше — то есть ЕЁ ЖЕ, пока волна
            # та же, — а сдвиг по кругу уступки идёт ПОСЛЕ этой сверки. Тупика в отказе нет: назвать
            # прежний адрес прямо — и объявление пройдёт тем же потоком.
            #
            # ‼️ Ключа принудительного затирания здесь нет ВОВСЕ, и заводить его нельзя. Он
            # разрушителен без нужды: сдача прежнего потока лежит в той же самой папке, ничего не
            # теряет и даёт тот же исход. А перегрузить им уже существующий ключ (у соседа он же
            # значит «сдать с непустым ящиком», и инструмент сам это советует) значит завести
            # привычку нажимать его не глядя. Вырезан весь класс, а не случай.
            if ($previous) {
                $prevWave = [string]$previous.Record.wave
                $prevStream = [string]$previous.Record.stream
                $otherStream = (
                    -not $previous.Closed -and $prevWave -and $prevStream -and
                    ($previous.WaveKey -ne $waveKey -or $previous.StreamKey -ne $streamKey)
                )
                if ($otherStream) {
                    $prevName = if ($previous.Record.name) { " «$($previous.Record.name)»" } else { '' }
                    $prevTasks = if ($previous.Record.tasks) { ", задачи $($previous.Record.tasks)" } else { '' }
                    # Ветку заявка знает не всегда (объявились из папки, откреплённой от ветки) —
                    # тогда об этом и говорим, а не выдаём пустое место за имя.
                    $prevBranch = if ($previous.Record.branch) {
                        ", ветка $($previous.Record.branch)"
                    } else {
                        ', ветка в заявке не названа'
                    }
                    Deny-Call @"
в этой рабочей папке уже числится другой поток: $prevWave/$prevStream$prevName$prevTasks — $($previous.State)$prevBranch, заявлен $(Format-Stamp -Raw $previous.Record.claimed_at).
Заявка на папку ОДНА: объявление потока $waveKey/$streamKey стёрло бы её молча — задачи прежнего потока выглядели бы невзятыми, находки ему не адресовали бы, а его сдача в конце закрыла бы чужую запись.
Прежний поток закончен — сдайте его прямо здесь: pwsh scripts/wave-board.ps1 -Mode Release
Это он и есть, объявляетесь заново — назовите его адрес: pwsh scripts/wave-board.ps1 -Mode Claim -Wave $prevWave -Stream $prevStream
Работа новая — заведите отдельное рабочее дерево и объявитесь из него.
"@
                }
            }
            # ‼️ ПРАВИЛО АДРЕСА: незакрытая ВЕДУЩАЯ заявка того же адреса из ДРУГОЙ рабочей папки —
            # отказ ДО записи. Два потока с одним адресом — корень всех следствий дефекта «переезд
            # раздваивает адрес»: занятый номер, приём находок на мёртвый адрес и произвольный
            # выбор, какую из двух записей считать настоящей. Отказ ставится там, где раздвоение
            # ещё не случилось; предупреждение ПОСЛЕ записи — ровно то, что сегодня не работает.
            #
            # ‼️ Правило действует только на НАЗВАННЫЙ номер. Там, где номер выдал сам инструмент
            # (в том числе унаследованный от своей же прежней записи — он остаётся выданным), номер
            # можно ДВИГАТЬ, и спор разрешает круг уступки ниже: он разрешает его корректно и без
            # человека. Тащить туда отказ значило бы ломать работающее.
            #
            # Закрытые в соперники не идут: у сданной вкладки больше нет, у перенесённой адрес уже
            # забран. Своя запись — тоже: её узнаём и по рабочей папке, и по файлу, потому что
            # заявка прежней версии из подкаталога лежит под неканоничным именем.
            $addressRivals = @($claims | Where-Object {
                    $_.WaveKey -eq $waveKey -and $_.StreamKey -eq $streamKey -and -not $_.Closed -and
                    (Get-FolderKey -Path $_.Record.worktree) -notin $hereKeys -and
                    (Get-FolderKey -Path $_.File) -ne (Get-FolderKey -Path $claimPath)
                })
            # Поле преемства и момент переноса наследуются наравне с остальными: без этого первое
            # же короткое переобъявление нового владельца стёрло бы пометку, и погашенная запись
            # воскресла бы вместе со своим адресом, своими именами и своим ящиком.
            #
            # ‼️ Наследуются они ТОЛЬКО при совпадении итогового адреса, и ниже, в круге уступки,
            # снимаются вместе со сдвигом номера. Поле называет папку, у которой забран ИМЕННО ЭТОТ
            # адрес; при другом адресе оно превращается в ложное ребро — заявка утверждает, что
            # забрала адрес у папки, которая его не вела, настоящее ребро при этом исчезает, а
            # погашенная запись воскресает.
            $takenFrom = ''
            $takenAt = ''
            if ($sameStream) {
                $takenFrom = [string]$previousSelf.Record.taken_from
                $takenAt = if ($previousSelf.Record.taken_at -is [datetime]) {
                    $previousSelf.Record.taken_at.ToString('s')
                } else {
                    [string]$previousSelf.Record.taken_at
                }
            }
            $takeOverNotes = [System.Collections.Generic.List[string]]::new()
            # Запись, у которой адрес забрали: у неё же наследуются имена ветки — находка, посланная
            # по прежнему имени потока, обязана дойти до новой папки вместе с самим потоком.
            $takenRival = $null
            if ($addressRivals.Count -gt 0 -and -not $streamAuto) {
                # Соперника берём старшего по тому же ПОЛНОМУ ключу, каким разрешается спор за
                # номер: у отказа и у переноса адресат обязан быть один и тот же.
                $rival = @($addressRivals | Sort-Object -Property @(
                        @{ Expression = { (Get-ClaimOrder -Claim $_.Record).When } }
                        @{ Expression = { (Get-ClaimOrder -Claim $_.Record).Path } }
                    ))[0]
                $rivalFolder = [string]$rival.Record.worktree
                $rivalKey = Get-FolderKey -Path $rivalFolder
                # Есть ли та папка на диске — улика, по которой человек за секунду отличает переезд
                # от спора с работающим соседом. ‼️ «Не видно» и «нет» не смешиваем: отвалившийся
                # диск и пропавшая сетевая шара отвечают тем же отказом, что и удалённая папка.
                $onDisk = switch ((Get-PathState -Path $rivalKey).Kind) {
                    'container' { 'папка на месте' }
                    'none' {
                        if (Test-PathReachable -Path $rivalKey) {
                            'папки на диске больше нет'
                        } else {
                            'путь к папке недостижим целиком — жива она или нет, неизвестно'
                        }
                    }
                    default { 'посмотреть, есть ли папка, не удалось' }
                }
                if (-not $TakeOver) {
                    # ‼️ Порядок выходов: безобидный ПЕРВЫМ, разрушительный ПОСЛЕДНИМ. Вкладка
                    # пользуется первым напечатанным, а случай живой — в реестре прямо сейчас
                    # открыты wave9/2 и wave9/2k, и различитель там выдумали руками через полдня.
                    $distinct = Get-DistinctStreamNumber -Claims $claims -WaveKey $waveKey -StreamKey $streamKey
                    $another = if ($distinct) {
                        "Другая нарезка той же волны — объявитесь своим номером: pwsh scripts/wave-board.ps1 -Mode Claim -Wave $waveKey -Stream $distinct"
                    } else {
                        "Другая нарезка той же волны — объявитесь своим номером: pwsh scripts/wave-board.ps1 -Mode Claim -Wave $waveKey -Stream <свободный номер>"
                    }
                    Deny-Call @"
адрес $waveKey/$streamKey уже ведёт незакрытая заявка ДРУГОЙ рабочей папки: $rivalFolder — $($rival.State), отметка $(Format-Stamp -Raw $rival.Record.seen_at), $onDisk.
Ведущая запись на адрес ОДНА: объявись вы второй, кому придёт находка, решал бы порядок описи каталога — половина адресованного пропала бы с бодрым рапортом об успехе.
$another
Тот поток закончен — сдайте его, встав ровно в его папку $($rivalFolder): pwsh scripts/wave-board.ps1 -Mode Release
Это ваш поток, вы переехали сюда (или перехватываете брошенную вкладку) — заберите адрес себе, у папки $rivalFolder он будет отнят: pwsh scripts/wave-board.ps1 -Mode Claim -Wave $waveKey -Stream $streamKey -TakeOver
"@
                }
                # Ключ назван — адрес переезжает. ‼️ Пишем ТОЛЬКО в свою заявку: чужой файл не
                # трогается ни байтом, и старая копия комплекта в соседнем дереве видит его ровно
                # таким, каким видела вчера.
                $takenFrom = $rivalFolder
                # ‼️ Момент переноса — СЕЙЧАС, даже если поле преемства унаследовано от прежнего
                # переезда: им решается, какие заявки этим ребром гасятся. Возьми мы прежний момент,
                # вернувшая себе адрес вкладка гасила бы записи, начавшиеся уже после того, как
                # адрес у неё забрали, — то есть и свежую заявку соседа, объявившегося законно.
                $takenAt = (Get-Date).ToString('s')
                $takenRival = $rival
                $takeOverNotes.Add("Адрес $waveKey/$streamKey забран у папки $rivalFolder ($($rival.State), отметка $(Format-Stamp -Raw $rival.Record.seen_at), $onDisk).")
                if ($rival.State -eq 'ведёт') {
                    # Громко: перехват у работающего соседа — законное, но названное действие, и
                    # обратимое (его файл не тронут, тем же ключом он вернёт адрес себе).
                    $takeOverNotes.Add('‼️ Та вкладка отмечалась только что — похоже, она работает. Адрес отнят у работающего соседа: убедитесь, что это ваш переезд, а не спор двух живых вкладок.')
                    $takeOverNotes.Add('   Ошиблись — сосед вернёт адрес себе тем же ключом: его заявка не тронута.')
                }
                if ($addressRivals.Count -gt 1) {
                    # Поле преемства называет ОДНУ папку, а записей оказалось больше: остальные
                    # остаются ведущими, и молчать об этом нельзя — адрес так и останется задвоенным.
                    $rest = @($addressRivals | Where-Object { $_ -ne $rival } |
                            ForEach-Object { [string]$_.Record.worktree }) -join ', '
                    $takeOverNotes.Add("‼️ Этот адрес ведут ещё записи других папок: $rest — они остались ведущими.")
                    $takeOverNotes.Add('   Сдайте каждую, встав ровно в её папку, иначе адрес останется задвоенным.')
                }
            } elseif ($TakeOver) {
                # Ключ назвали, а переносить нечего. Молчать нельзя: вкладка думает, что забрала
                # адрес, и скажет об этом соседям. Причин ровно две, и путать их нельзя.
                if ($addressRivals.Count -gt 0) {
                    $takeOverNotes.Add("‼️ Ключ переноса не сработал: номер $streamKey выдан инструментом, а не назван вами.")
                    $takeOverNotes.Add('   На выданный номер перенос не распространяется — там номер можно двигать, и спор разрешает круг уступки сам. Назовите номер потока явно, если адрес и вправду ваш.')
                } else {
                    $takeOverNotes.Add('Ключ переноса не понадобился: этот адрес не ведёт заявка другой папки.')
                }
            }
            # ‼️ Прежние имена ветки переносим в новую заявку. Объявиться можно второй раз, и
            # объявление молча переписывает заявку: переименуй вкладка ветку и объявись заново —
            # старое имя стёрлось бы отовсюду, а находка, УЖЕ ПРИНЯТАЯ по нему, не дошла бы и
            # сдачу не задержала. Держим немного: имя нужно, пока живёт волна, а не вечно.
            #
            # ‼️ Наследует имена тот, у кого совпал АДРЕС, а не тот, кто сел в ТУ ЖЕ ПАПКУ. Имя
            # ветки — это способ адресовать находку ПОТОКУ, значит оно принадлежит потоку, а не
            # рабочей папке: папку переиспользуют, а поток вместе с ней не переходит. Отсюда две
            # симметричные беды безусловного переноса: поток сдали, из той же папки объявился
            # следующий — и он начинал отзываться на имя сданного и перехватывать его находки; а
            # переехавшая вкладка, наоборот, память имён теряла, потому что в новой папке наследовать
            # было не у кого. Совпали волна И номер — это тот же поток объявляется заново, и имена
            # его собственные; разошлись — это другой поток, и чужие имена ему не положены.
            #
            # ‼️ И заявка при этом обязана быть НЕЗАКРЫТОЙ (признак `$sameStream` считается выше, по
            # своей прежней незакрытой). Сданная того же адреса имён не отдаёт: вкладки, которая
            # вела тот поток, больше нет, а следующий поток в этой папке — другой. Не смотри мы на
            # состояние, новый жилец папки отзывался бы на имя сданного соседа и получал бы
            # адресованные тому находки — ровно та беда, ради которой наследование и привязано к
            # адресу, только зашедшая с другой стороны. Инструмент вдобавок обещает при сдаче, что
            # находки сданному больше не примут, — обещание надо держать.
            #
            # ‼️ При переносе адреса имена наследуются у той записи, У КОТОРОЙ адрес забрали. Ящик —
            # это работа, а не бухгалтерия: перенос адреса без переноса имён был бы той же потерей,
            # только с другой стороны — находка, УЖЕ ПОСЛАННАЯ по прежнему имени ветки потока, не
            # дошла бы до папки, куда поток переехал. Адрес у обеих записей один и тот же, значит и
            # поток один: правило «имена принадлежат потоку, а не папке» тут не нарушено.
            $inheritNamesFrom = [System.Collections.Generic.List[object]]::new()
            # ‼️ Своя запись — та же, у которой взяты имя и задачи: и открытая, и перенесённая.
            # У вернувшейся вкладки память имён СВОЯ, и терять её при возврате нельзя — находка,
            # уже посланная по прежнему имени её ветки, иначе не дошла бы ни до кого.
            if ($sameStream) { $inheritNamesFrom.Add($previousSelf.Record) }
            if ($takenRival) { $inheritNamesFrom.Add($takenRival.Record) }
            $former = [System.Collections.Generic.List[string]]::new()
            foreach ($source in $inheritNamesFrom) {
                $earlier = @([string]$source.branch) + @($source.former_branches)
                foreach ($name in $earlier) {
                    # ‼️ Ничего не вытесняем. Вытесненное имя означало бы находку, УЖЕ ПРИНЯТУЮ по
                    # нему, которая перестала доставляться и перестала держать сдачу, — то есть
                    # тихую потерю, ради предотвращения которой память и заводилась. Растёт список
                    # только от настоящих переименований ветки, а это единицы за волну.
                    if ($name -and $name -ne $branch -and $name -notin $former) { $former.Add($name) }
                }
            }
            $claim = [ordered]@{
                wave            = $waveKey
                stream          = $streamKey
                # ‼️ Признак «волна подставлена сама». По нему и только по нему соседняя вкладка
                # решает, можно ли присоединиться к этой волне. Заявки старого вида его не несут —
                # и правильно: они заводились с названной волной, где номера идут из плана.
                wave_auto       = $waveAuto
                name            = $claimName
                tasks           = $claimTasks
                plan            = $claimPlan
                branch          = $branch
                # Имена, под которыми поток знали раньше: находка, посланная по ним, обязана дойти.
                former_branches = @($former)
                worktree        = $tree
                claimed_at      = $claimedAt
                seen_at         = (Get-Date).ToString('s')
                state           = 'open'
            }
            if ($takenFrom) {
                # ‼️ Поле кладём ТОЛЬКО когда перенос был. Пустое поле у каждой заявки — это шум,
                # который разновозрастные копии комплекта прочтут по-разному; отсутствие поля читают
                # все одинаково: «переноса не было».
                $claim.taken_from = $takenFrom
                # Момент рядом с папкой: по нему решается, какие заявки это ребро гасит. Пусто он
                # бывает ровно в одном случае — поле унаследовано у заявки прежней версии, которая
                # писала одну лишь папку; тогда ребро действует безусловно, как и до этого правила.
                if ($takenAt) { $claim.taken_at = $takenAt }
            }
            # ‼️ ПРОШЛЫЕ переезды прежней заявки ЭТОЙ ПАПКИ переезжают в новую заявку. Заявка на
            # папку одна, и без этого списка объявление следующего потока стирало бы ребро вместе с
            # файлом: брошенная запись прежней папки снова становилась бы ведущей — молча, с
            # рапортом «дойдёт сама» у приёма и с находкой, принесённой брошенной вкладке. Тем же
            # убивало и цепочку A→B→C, стоило переобъявиться СРЕДНЕЙ папке.
            #
            # Список наследуется от ЛЮБОЙ прежней заявки этой папки — и от сданной, и от
            # перенесённой, и от своей же незакрытой: переезд это событие в истории АДРЕСА, а
            # список хранит адрес каждого переезда отдельно от нынешнего адреса заявки.
            #
            # ‼️ Совместимость со старыми копиями неполная, и врать об этом нельзя. ЧИТАЮТ они
            # незнакомые поля терпимо: сторож доставки старой копии переписывает файл заявки на
            # каждом ходу и память переездов при этом сохраняет — это проверено набором. А вот
            # ПОЛНОЕ объявление старой копией в этой же папке пересобирает заявку из своего
            # фиксированного набора полей и стирает и список прошлых переездов, и нынешнее поле
            # преемства: призрак прежней папки молча снова становится ведущим. Лечится это только
            # развозом правки по всем копиям комплекта. Чужие файлы заявок при этом по-прежнему не
            # трогаются ни байтом — не тронет их и старая копия.
            $droppedTakeovers = @()
            $pastTakeovers = @(Get-ClaimPastTakeovers `
                    -Previous $(if ($previous) { $previous.Record } else { $null }) `
                    -Wave $waveKey -Stream $streamKey -From $takenFrom -Dropped ([ref]$droppedTakeovers))
            if ($pastTakeovers.Count -gt 0) { $claim.past_takeovers = @($pastTakeovers) }
            foreach ($gone in $droppedTakeovers) {
                # Отброшенное по пределу памяти — вслух, в той же команде: молчаливая потеря ребра
                # воскрешает брошенную запись прежней папки, и больше об этом не скажет никто.
                $takeOverNotes.Add("‼️ Память переездов переполнена ($(Get-PastTakeoverLimit)) — самый старый переезд забыт: адрес $($gone.Wave)/$($gone.Stream), забран у папки $($gone.From).")
                $takeOverNotes.Add('   Если запись той папки ещё лежит в реестре, она снова станет ведущей на том адресе — сдайте её, встав в её папку.')
            }
            if ($waveSource -eq 'own' -and -not $waveAutoKnown) {
                # Заявка прежней версии признака не несёт, и переобъявление не вправе решать за неё:
                # заведи мы поле сейчас — заявка сменила бы вид, а вместе с ним и ответы на «есть ли
                # план» и «можно ли присоединиться к этой волне».
                $claim.Remove('wave_auto')
            }
            Write-ClaimFile -Path $claimPath -Claim $claim
            # Круг разрешения спора за номер. Под замком соперника здесь обычно НЕ находится:
            # реестр прочитан с уже записанными заявками соседей, и выбранный номер свободен. Круг
            # оставлен на случаи, где замка нет:
            #   • замок не отдали за отведённое время (о чём вкладка говорит вслух ниже) — тогда это
            #     единственная защита от двух потоков с одним адресом;
            #   • заявка соседа появилась ПОСЛЕ нашей — например, её вернули из резервной копии или
            #     принесла вкладка версии без замка.
            #
            # Разрешается спор сдвигом СВОЕГО номера: файл заявки принадлежит только этой вкладке,
            # перезаписать его безопасно. Уступает объявившийся позже (при равном времени — чей путь
            # дерева меньше по алфавиту): порядок полный и неизменный, поэтому две вкладки не
            # сдвигаются одновременно и не меняются номерами без конца.
            $movedFrom = ''
            # ‼️ Всё, что идёт ПОСЛЕ записи своей заявки, прикрыто одинаково: строгое чтение, а
            # неудача — не отказ, а громкое предупреждение. Отказывать здесь уже нельзя — заявка
            # легла, поток объявлен, и «объявиться не вышло» было бы неправдой, да ещё и с открытой
            # заявкой в реестре. Прежде так был прикрыт только последний снимок, а круг разрешения
            # спора — нет, и помеха, начавшаяся сразу после записи, давала ровно ту неправду,
            # которой прикрытие и заводилось избегать.
            $snapshotFailed = ''
            try {
                # Заходов несколько: сдвинувшись, можно попасть на номер, который в ту же
                # секунду занял третий сосед. Порядок разрешения у всех один, поэтому заходы
                # сходятся, а не кружат.
                for ($round = 1; $round -le 5; $round++) {
                    # Тоже строго: круг спора читает тот же реестр и решает тот же вопрос.
                    $claims = @(Get-Claims -Dir $registry -Strict)
                    $rivals = @(Get-NumberRivals -Claims $claims -WaveKey $waveKey -StreamKey $streamKey -TreePath $tree)
                    if ($rivals.Count -eq 0) { break }
                    # Названный номер идёт из плана — он и есть имя потока, им адресуют находки, и
                    # двигать его нельзя. Такой спор разрешает человек, о нём инструмент и
                    # говорит ниже.
                    if (-not $streamAuto) { break }
                    if (-not (Test-YieldsStreamNumber -Mine $claim -Rivals $rivals)) { break }
                    if (-not $movedFrom) { $movedFrom = $streamKey }
                    $streamKey = Get-FreeStreamNumber -Claims $claims -WaveKey $waveKey -TreePath $tree
                    $claim.stream = $streamKey
                    # ‼️ Адрес разошёлся с тем, у которого он был забран, — значит поле преемства
                    # больше не про НЫНЕШНИЙ адрес. Оставь мы его как есть — заявка утверждала бы,
                    # что забрала адрес у папки, которая его никогда не вела: настоящее ребро
                    # переноса исчезает, а погашенная им запись воскресает вместе со своим ящиком.
                    # Ключ переноса сюда не доходит (он идёт только с НАЗВАННЫМ номером, а такой
                    # круг уступки не двигает), поэтому здесь всегда сдвигается унаследованное поле.
                    #
                    # ‼️ Но и просто выбросить его нельзя: переезд БЫЛ, и запись прежней папки им
                    # погашена. Выбрось мы память — призрак воскрес бы ровно так же, только с другой
                    # стороны. Поэтому переезд уходит в список прошлых ВМЕСТЕ СО СВОИМ АДРЕСОМ —
                    # тем, который поток вёл до сдвига; у адреса, с которого поток ушёл, ведущей
                    # записи не останется вовсе, и это правильно: поток уехал и там закончился.
                    if ($claim.Contains('taken_from') -and $claim.taken_from) {
                        $movedTakeover = [ordered]@{
                            wave       = $waveKey
                            stream     = $movedFrom
                            # Папку кладём приведённой — тем же видом, каким её пишет сборка списка
                            # прошлых переездов: два вида одной папки схлопнуться не смогут, и
                            # переезд лежал бы в списке дважды.
                            taken_from = (Get-FolderKey -Path ([string]$claim.taken_from))
                        }
                        if ($claim.Contains('taken_at') -and $claim.taken_at) {
                            $movedTakeover.taken_at = [string]$claim.taken_at
                        }
                        $claim.past_takeovers = @(
                            @(@($claim.past_takeovers) | Where-Object { $_ }) + @($movedTakeover)
                        )
                    }
                    $claim.Remove('taken_from')
                    $claim.Remove('taken_at')
                    Write-ClaimFile -Path $claimPath -Claim $claim
                }
                # ‼️ Снимок для рапорта берём ПОСЛЕДНИМ и ПОД ЗАМКОМ. Последним — потому
                # что пока шёл спор за номер, сосед мог сдвинуться сам, и предупреждать о нём
                # было бы неправдой. Под замком — потому что по этому снимку печатается
                # единственная защита от двух вкладок на ОДНОМ НАЗВАННОМ номере: такой номер
                # идёт из плана, двигать его нельзя, и всё, что остаётся, — сказать человеку
                # «на этот же поток есть заявка другого дерева». Им же печатается карта
                # соседей: пустой снимок означает вкладку, уверенную, что она одна.
                $claims = @(Get-Claims -Dir $registry -Strict)
                # Имена волн для разбора адреса — из ЭТОГО снимка: ниже по нему же ищутся записи,
                # оставленные потоку впрок, а их адрес может звать волну словом.
                Set-KnownWaves -Keys @($claims | ForEach-Object { $_.WaveKey })
            } catch {
                $snapshotFailed = $_.Exception.Message
                $claims = @()
            }
        } finally {
            # Замок снимаем ВСЕГДА: иначе сорвавшаяся вкладка держала бы объявление соседей до
            # конца своей жизни.
            Exit-RegistryLock -Handle $lockHandle
        }
        $rivals = @(Get-NumberRivals -Claims $claims -WaveKey $waveKey -StreamKey $streamKey -TreePath $tree)
        "Поток $waveKey/$streamKey объявлен за этой вкладкой (ветка $branch)."
        # Перенос адреса — первым делом после самого объявления: это единственное, что механизм
        # сделал ЗА вкладку и что затрагивает соседа, а всё сделанное сам он обязан говорить вслух в
        # той же команде, где это случилось.
        foreach ($note in $takeOverNotes) { $note }
        # ‼️ ОБЪЯВЛЕНИЕ ПЕРЕЧИТЫВАЕТ РЕЕСТР И ГОВОРИТ ПРАВДУ. Заявка легла в свой файл — но ведущая
        # она или уже погашена, решает реестр КАК ЦЕЛОЕ, а не файл: чужое ребро переноса могло
        # погасить её в тот же миг. Так бывает при равной секунде (сторона неопределённости выбрана
        # в пользу действия ребра — это верно) и в круге возврата, уложившемся в секунду: вкладка
        # выполнила напечатанную ей самим механизмом команду и получила бы бодрый рапорт об успехе,
        # хотя снаружи её не существует.
        #
        # Правило здесь общее, а не заплатка на две сцены: тихим успехом не рапортуем НИГДЕ, где
        # механизм решил за человека. Любой будущий способ погасить свою запись при объявлении
        # назовётся вслух сам собой.
        # Своя запись вышла погашенной — объявление кончается ОТКАЗОМ, а не тихим нулём. Ставится
        # здесь, печатается в самом конце: сперва вкладка дочитывает всё, что механизм ей говорит.
        $quenchedAtWrite = $false
        if (-not $snapshotFailed) {
            $mineNow = Get-ClaimEntry -Claims $claims -Claim $claim -Path $claimPath
            if ($mineNow -and $mineNow.Superseded) {
                $quenchedAtWrite = $true
                $fate = Get-ClaimAddressFate -Claim $mineNow
                # Момент — ТОГО САМОГО переезда, которым запись погашена, а не нынешних полей
                # забравшей заявки: у неё переездов может быть несколько, и они о другом.
                $whenTaken = if ($mineNow.TakenAt) {
                    "перенос $(Format-Stamp -Raw $mineNow.TakenAt)"
                } else {
                    'момента переноса та заявка не называет — она прежней версии'
                }
                "‼️ Ваша запись сразу же ПОГАШЕНА чужим переносом: $($fate.Text) ($whenTaken)."
                '   Снаружи этой вкладки не существует: находки по адресу ей не принесут, а её сдача скажет, что сдавать нечего.'
                # ‼️ Ключ переноса советуем ТОЛЬКО когда адрес и вправду кто-то ведёт: он забирает
                # адрес у ведущей заявки другой папки, а её тут может не быть вовсе — тогда ключ
                # честно ответит «не понадобился», и вкладка пойдёт по кругу, выполняя единственный
                # напечатанный ей выход. Напечатанный выход обязан работать.
                if ($fate.StillLed) {
                    "   Адрес и вправду ваш — заберите его обратно: pwsh scripts/wave-board.ps1 -Mode Claim -Wave $waveKey -Stream $streamKey -TakeOver"
                } else {
                    '   Забрать адрес обратно нечем: ведущей записи у него не осталось — папка, забравшая его, ушла дальше или закончила поток.'
                }
                "   Спорить не о чем — объявитесь свободным номером: pwsh scripts/wave-board.ps1 -Mode Claim -Wave $waveKey -Stream <свободный номер>"
            }
            # То же самое про адрес целиком: ведущей записи у него может не остаться вовсе — так
            # выглядит адрес, чей поток переехал и там закончился. Исход законный, но невидимым
            # быть не должен: находку по такому адресу приём не примет.
            $leading = @($claims | Where-Object {
                    $_.WaveKey -eq $waveKey -and $_.StreamKey -eq $streamKey -and -not $_.Closed
                })
            if ($leading.Count -eq 0) {
                "‼️ У адреса $waveKey/$streamKey не осталось ни одной ведущей записи — находку по нему приём не примет, а соседям он не адресуем."
                '   Разберитесь по показу, куда уехал поток: pwsh scripts/wave-board.ps1 -Mode Streams'
            }
        }
        if ($snapshotFailed) {
            "‼️ Реестр заявок для сверки с соседями прочитать не удалось: $snapshotFailed"
            '   Поток объявлен, но предупреждение о совпадении номера и карта соседей не построены — сверьте вручную: -Mode Streams'
        }
        if (-not $lockHandle) {
            # Молчать об этом нельзя: без замка номер выбирался по снимку, который сосед мог
            # обогнать, — ровно тот случай, когда два потока получают один адрес и обе стороны об
            # этом не узнают.
            "‼️ Замок реестра заявок не отдали за $(Get-RegistryLockWaitSeconds) с — номер потока выбран без него, он может совпасть с соседним."
            '   Сверьте адреса: -Mode Streams. Похоже, соседняя вкладка застряла посреди объявления.'
        }
        # Строка про продолжение своего потока. Собирается ЗДЕСЬ, потому что печатается из двух
        # мест: волну не называли — она идёт хвостом к четвёртому источнику волны; назвали — сама
        # по себе, ниже.
        #
        # ‼️ Адрес в ней — тот, который поток ВЁЛ, а не тот, что вышел после круга уступки. Круг
        # мог сдвинуть номер уже после опознания потока, и печатать нынешний как продолжаемый
        # значило бы назвать вкладке адрес, которого у неё не было никогда: «продолжаете поток
        # волна/2, заявленный вчера» — а вчера она была волна/1. Следующей строкой инструмент сам
        # говорит про сдвиг, но первой строке верят раньше, чем дочитывают до второй.
        $ownName = if ($claim.name) { " «$($claim.name)»" } else { '' }
        $ownAddress = if ($movedFrom) { "$waveKey/$movedFrom" } else { "$waveKey/$streamKey" }
        $ownMoved = if ($movedFrom) { ' — номер уступлен соседу, новый адрес назван ниже' } else { '' }
        $continued = "Продолжаете поток $ownAddress$ownName, заявленный $(Format-Stamp -Raw $claim.claimed_at)$ownMoved."
        # Откуда взялась волна — говорим вслух. Подставленную молча вкладка выдаст владельцу за
        # названную им, а соседям назовёт адрес, которого не ждала ни одна сторона.
        switch ($waveSource) {
            'date' {
                "Волна не названа — взята по сегодняшней дате. Адрес потока для соседей: $waveKey/$streamKey."
            }
            'joined' {
                # Считаем потоки волны ПОСЛЕ присоединения, вместе со своим: вкладка спрашивает
                # «сколько нас», а не «сколько было до меня».
                $inWave = @(@($claims | Where-Object { $_.WaveKey -eq $waveKey } |
                            ForEach-Object { $_.StreamKey }) + $streamKey |
                        Where-Object { $_ } | Select-Object -Unique)
                "Волна не названа — вкладка присоединена к уже идущей работе $waveKey, в ней потоков: $($inWave.Count)."
            }
            'plan' {
                'Волна взята из имени плана.'
            }
            'own' {
                # Четвёртый источник волны. Молчать о нём нельзя ровно по той же причине, что и о
                # трёх остальных: вкладка объявилась коротко, а получила адрес, имя и задачи,
                # которых в вызове не называла, — и назовёт их соседям как свои.
                "Волна не названа — унаследована от вашей прежней записи. $continued"
                '   Работа другая — сдайте прежний поток здесь же (-Mode Release) и объявитесь заново.'
            }
        }
        if ($sameStream -and $waveSource -ne 'own') {
            # Волну (или путь плана) назвали, а всё остальное вкладка взяла у своей прежней записи.
            # Говорим об этом ровно так же, как о четвёртом источнике волны: молчание тут стоило бы
            # того же — вкладка получила имя, задачи и старшинство, которых в вызове не называла.
            $continued
            '   Работа другая — сдайте прежний поток здесь же (-Mode Release) и объявитесь заново.'
        }
        # Про выданный номер говорим, только если его и вправду выдали. Унаследованный у своей же
        # записи выдан не сейчас, а в прошлый раз, и назвать его «следующим свободным» значило бы
        # соврать вкладке о собственном адресе. Сдвинутый кругом уступки — снова выданный, о нём
        # говорим по-прежнему.
        if ($streamAuto -and (-not $streamInherited -or $movedFrom)) {
            "Номер потока не назван — выдан следующий свободный: $streamKey."
        }
        if ($movedFrom) {
            "‼️ Номером $waveKey/$movedFrom в тот же миг объявилась соседняя вкладка — ваш поток сдвинут на следующий свободный: $waveKey/$streamKey."
            '   Соседям называйте новый адрес: по старому находка уйдёт чужому потоку.'
        }
        # Номер, которым потом нельзя адресовать. Разбор адреса требует справа НОМЕР, а объявление
        # принимает в это поле любое слово: такой поток адресуют только запасным путём (именем
        # ветки), а имена к середине волны врут. Не отказываем — предупреждаем сразу, пока вкладка
        # не назвала соседям адрес, которого не существует.
        if ($Stream -and -not (Get-StreamAddress -Raw "1/$Stream")) {
            "‼️ Номером «$Stream» адресовать поток нельзя: справа от косой черты разбирается только номер (3, П3, 3b)."
            '   Назовите номер потока из плана — иначе находку соседи основным способом не пошлют.'
        }
        # Записи, оставленные потоку впрок, пока его не открывали. Сторож доставки принесёт их
        # ближайшим ходом, но сказать о них здесь стоит: заявка — тот самый момент, когда вкладка
        # узнаёт, что её уже ждали.
        $waiting = @(Select-ForStream -Records (Get-OpenRecords -Path $board -Viewer (Get-CurrentKeys)) `
                -Keys (Get-CurrentKeys) -Claim $claim)
        if ($waiting.Count -gt 0) {
            "Вас уже ждут записи на доске: $($waiting.Count) — придут ближайшим ходом."
        }
        # Чужая живая заявка на тот же поток, которая осталась и после разрешения спора (номер
        # назван, а не выдан, — двигать его нельзя). Не отказ: перехват вкладки бывает осознанным,
        # первую могли закрыть, не сдав. Но и молчать нельзя — два потока с одним номером
        # раздваивают адресацию, и половина находок уходит не туда.
        foreach ($rival in $rivals) {
            "‼️ На этот же поток есть открытая заявка другого дерева: $($rival.Record.worktree) — $($rival.State)."
            '   Два потока с одним номером раздваивают адресацию: разберитесь, чья вкладка ведёт его на самом деле.'
        }
        # Карта соседей печатается сразу, а не по запросу: вкладка узнаёт границы своей работы в
        # первую же минуту. Без неё она предлагает владельцу взять соседнюю задачу, а владелец не
        # знает, что задачу планировали другому потоку, и подтверждает.
        $neighbours = @($claims | Where-Object {
                $_.WaveKey -eq $waveKey -and (Get-FolderKey -Path $_.Record.worktree) -ne (Get-FolderKey -Path $tree)
            })
        if ($neighbours.Count -gt 0) {
            ''
            "Соседние потоки волны ${waveKey}:"
            foreach ($neighbour in $neighbours) { Format-ClaimLine -Claim $neighbour }
            'Работа за пределами своих задач — сперва посмотрите, чей это кусок: -Mode Streams -Task <номер>.'
        }
        if ($quenchedAtWrite) {
            # ‼️ ОТКАЗ, а не успех: снаружи этой вкладки не существует, и нулевой код прочитался бы
            # как «объявился, работаю». Файл заявки при этом ЗАПИСАН — об этом сказано выше, и
            # повторять команду не надо: она даст ровно тот же исход. Ни один сторож комплекта,
            # установщик и заготовка задания кода объявления не читают (проверено), поэтому цена
            # отказа здесь — только правда, сказанная тем способом, который нельзя не заметить.
            #
            # Печатается ПОСЛЕДНИМ и в поток ошибок, как все отказы инструмента.
            [Console]::Error.WriteLine("объявиться не вышло: запись потока $waveKey/$streamKey погашена чужим переносом в тот же миг. Файл заявки записан, но снаружи вкладки не существует — выходы напечатаны выше.")
            exit 1
        }
    }

    'Release' {
        # Сдача потока. Здесь единственный раз задаётся вопрос «всё ли до меня дошедшее учтено» —
        # без него запись, положенная за десять минут до закрытия вкладки, не достаётся никому и
        # никогда, а отправителю уже отрапортовали об успехе.
        # ‼️ Корень дерева — строго и первым делом, как и в объявлении: по нему ищется своя заявка.
        # Молчаливый откат на текущую папку бьёт здесь в самое дорогое место — сдача не находит
        # заявки и выходит УСПЕХОМ, вкладка закрывается, а поток остаётся числиться живым.
        $tree = Get-TreeRoot -Strict
        # ‼️ СДАЧА СИРОТЫ ПО АДРЕСУ. Это ЕДИНСТВЕННАЯ операция комплекта, которая пишет в ЧУЖОЙ
        # файл заявки, и разрешена она ровно в одном положении: каталога записи НЕТ на диске, а
        # путь при этом достижим.
        #
        # Условие выбрано не по молчанию, а по ОТСУТСТВИЮ ПИСАТЕЛЯ. У файла заявки есть второй
        # писатель — сторож доставки той папки: он читает документ целиком и пишет целиком, на
        # каждом ходу вкладки, замка не берёт и взять не может. В несуществующей папке он
        # запуститься не может вовсе, значит писателя нет и гонки не бывает. Молчание отметки
        # таким доказательством не является НИКОГДА: оно доказывает ровно одно — вкладка не делала
        # ходов, а прогон субагентов, ожидание сборки и ночная пауза выглядят так же.
        #
        # ‼️ «Не вижу» и «нет» здесь не одно и то же, и смешивать их запрещено: отвалившийся диск и
        # пропавшая сетевая шара отвечают тем же отказом, что и удалённая папка. Разводим их тем же
        # приёмом, каким разведены в правиле адреса, — достижимостью пути.
        #
        # Свой поток сдаётся из своей папки и ключей не требует вовсе; здесь они значат «сдать
        # запись, которая осталась от исчезнувшей вкладки».
        if ($Wave -or $Stream) {
            if (-not $Wave -or -not $Stream) {
                Deny-Call 'сдача по адресу требует и волну, и номер потока: -Mode Release -Wave <волна> -Stream <номер>. Свой поток сдаётся из своей рабочей папки, без ключей вовсе.'
            }
            $wantWave = Get-WaveKey -Raw $Wave
            $wantStream = Get-StreamNumberKey -Raw $Stream
            $address = "$wantWave/$wantStream"
            # Под замком реестра: ту же запись в этот самый миг может забирать ключом переноса
            # соседняя вкладка. Замка не дали — говорим вслух и идём дальше, как объявление:
            # решение принимается по прочитанному снимку, а он полезен и без замка.
            $lockHandle = Enter-RegistryLock -Dir $registry
            try {
                # ‼️ Строго: по этому снимку решается судьба ЧУЖОЙ записи. Не увидеть соседа здесь
                # значит счесть исчезнувшим того, чей файл в этот миг просто занят.
                $all = @(Get-Claims -Dir $registry -Strict)
                Set-KnownWaves -Keys @($all | ForEach-Object { $_.WaveKey })
                $orphans = @($all | Where-Object {
                        $_.WaveKey -eq $wantWave -and $_.StreamKey -eq $wantStream -and -not $_.Closed
                    })
                if ($orphans.Count -eq 0) {
                    Deny-Call @"
незакрытой записи с адресом $address в реестре нет — сдавать по этому адресу нечего.
Кто какой поток ведёт: pwsh scripts/wave-board.ps1 -Mode Streams
"@
                }
                if ($orphans.Count -gt 1) {
                    # Выбирать за человека нельзя: сдали бы наугад одну, а вторая осталась бы
                    # держать адрес живым — то есть принимать находки, которые не достанутся
                    # никому. Называем каждую вместе с её файлом: по файлу владелец найдёт её
                    # руками, даже если папки уже нет.
                    $listed = @($orphans | ForEach-Object {
                            "$(Format-ClaimLine -Claim $_)`n    файл заявки: $($_.File)"
                        }) -join "`n"
                    Deny-Call @"
адрес $address ведут сразу несколько незакрытых записей ($($orphans.Count)) — какую из них сдавать, механизм решать не вправе.
$listed
Сдайте каждую, встав ровно в её рабочую папку: pwsh scripts/wave-board.ps1 -Mode Release
Папки записи на диске уже нет — уберите её файл заявки руками, путь назван выше.
"@
                }
                $orphan = $orphans[0]
                $orphanFolder = [string]$orphan.Record.worktree
                $orphanKey = Get-FolderKey -Path $orphanFolder
                $folderState = Get-PathState -Path $orphanKey
                switch ($folderState.Kind) {
                    'none' {
                        if (-not (Test-PathReachable -Path $orphanKey)) {
                            Deny-Call @"
путь к рабочей папке потока $address недостижим целиком: $orphanFolder — жива она или нет, неизвестно.
Отвалившийся диск и пропавшая сетевая шара отвечают тем же отказом, что и удалённая папка, а писать в чужую заявку можно ровно там, где писателя ЗАВЕДОМО не существует.
Верните путь (подключите диск или сетевую шару) и повторите.
"@
                        }
                    }
                    'container' {
                        Deny-Call @"
рабочая папка потока $address на месте: $orphanFolder — идите в неё и сдайте поток оттуда: pwsh scripts/wave-board.ps1 -Mode Release
Ключа обхода здесь нет и не будет: у заявки в живой папке есть второй писатель — сторож доставки той вкладки, — и пометка о сдаче стёрлась бы его ближайшей отметкой живости уже ПОСЛЕ того, как нам отрапортовали об успехе.
Запись молчит ($($orphan.State), отметка $(Format-Stamp -Raw $orphan.Record.seen_at)) — это не доказательство: вкладка могла гонять субагентов, ждать сборки или простоять ночь.
"@
                    }
                    default {
                        $why = if ($folderState.Reason) { $folderState.Reason } else { 'причина неизвестна' }
                        Deny-Call @"
посмотреть, есть ли рабочая папка потока $address ($orphanFolder), не удалось: $why.
Сдавать чужую запись вслепую нельзя: писать в неё можно ровно там, где папки заведомо нет, а писателя не существует.
"@
                    }
                }
                # Папки нет, путь достижим — писателя не существует, и запись можно закрыть.
                if (-not $lockHandle) {
                    # Замок не дали. Записи в ЧУЖОЙ файл это не касается — писателя там нет вовсе,
                    # — но соседняя вкладка могла в эти же секунды забрать адрес ключом переноса, и
                    # тогда решение принято по снимку, устаревшему на её заявку. Молчать нельзя:
                    # всё, что механизм решил сам, он говорит вслух в той же команде.
                    "‼️ Замок реестра заявок не отдали за $(Get-RegistryLockWaitSeconds) с — запись сдана по снимку, снятому без него."
                }
                $orphanRecord = $orphan.Record
                # Через `Add-Member -Force`, а не присваиванием: заявка сироты могла быть заведена
                # прежней версией, у которой поля состояния нет вовсе, — присваивание сорвалось бы,
                # и сирота осталась бы держать адрес живым.
                $orphanRecord | Add-Member -NotePropertyName state -NotePropertyValue 'released' -Force
                $orphanRecord | Add-Member -NotePropertyName released_at -NotePropertyValue ((Get-Date).ToString('s')) -Force
                # ‼️ След «кто сдал». Своя сдача его не пишет — там сдавший и владелец одна и та же
                # вкладка. Здесь запись закрыл ПОСТОРОННИЙ, и без следа это выглядело бы как честная
                # сдача самой вкладкой: владелец не смог бы отличить одно от другого никогда.
                $orphanRecord | Add-Member -NotePropertyName released_from -NotePropertyValue $tree -Force
                Write-ClaimFile -Path $orphan.File -Claim $orphanRecord
                "Запись $address сдана по адресу: рабочей папки $orphanFolder на диске нет, писателя у её заявки не существует."
                "След в записи: сдана $(Format-Stamp -Raw $orphanRecord.released_at) из папки $tree."
                'Находки этому потоку больше не примут.'
                # Что осталось в ящике сироты — вслух и здесь же. Вкладки, которая это разберёт,
                # больше нет, поэтому отказывать и звать ключ незачем: разбирать придётся руками
                # тому, кто сдаёт. Промолчи мы — находки исчезли бы вместе с адресом, а их авторам
                # уже отрапортовали об успехе.
                $content = Read-BoardContent -Path $board
                if ($content.Ok) {
                    $orphanKeys = @(Get-StreamNames -Claim $orphanRecord -Claims $all)
                    $onBoard = @(Select-OpenEntries -Entries (Get-BoardEntries -Lines $content.Lines) -Viewer $orphanKeys |
                            ForEach-Object { $_.Record })
                    # Уведомления «учтено» не считаем: они гаснут сами при показе и работы не несут.
                    $waiting = @(Select-ForStream -Records $onBoard -Keys $orphanKeys -Claim $orphanRecord |
                            Where-Object { [string]$_.kind -ne 'ack' })
                    if ($waiting.Count -gt 0) {
                        "‼️ В ящике сданной записи осталось открытым: $($waiting.Count) — им теперь некуда прийти, разберите их руками."
                        foreach ($record in $waiting) { Format-BoardRecord -Record $record }
                    }
                } else {
                    "‼️ Доску прочитать не удалось ($($content.Reason)) — что осталось в ящике этой записи, здесь не сказано."
                }
            } finally {
                # Замок снимаем ВСЕГДА, и на отказе тоже: иначе сорвавшаяся вкладка держала бы
                # объявление соседей до конца своей жизни.
                Exit-RegistryLock -Handle $lockHandle
            }
            return
        }
        $claimPath = Get-ClaimPath -Dir $registry -TreePath $tree
        # Строго: «заявки нет» и «файл занят» ведут отсюда в противоположные стороны, а выглядят
        # одинаково — пустотой. Своя заявка читается ПЕРВОЙ: испорчена именно она — владелец
        # должен получить отказ про СВОЙ файл с его путём, а не общий отказ про заявку соседа.
        $mine = Get-CurrentClaim -Dir $registry -Strict
        # ‼️ «Заявки нет» — правда только тогда, когда реестр ЧИТАЕТСЯ. На мёртвом пути (отвалился
        # диск, пропала шара) отсутствие своего файла выглядит точно так же, и вкладке говорили
        # «сдавать нечего» кодом успеха. Реестр спрашиваем строго: он и отличит «заявок нет» от
        # «посмотреть не смогли». Читаем его ЗДЕСЬ, потому что по нему же ищется запись этой папки.
        $all = @(Get-Claims -Dir $registry -Strict)
        $claim = $null
        # ‼️ ПЕРВОЙ идёт запись, чья записанная рабочая папка ТОЧНО равна той, из которой сдают, и
        # только потом — каноничный ключ (корень дерева). Порядок именно такой, потому что показ
        # печатает папку ИЗ ЗАПИСИ и единственный напечатанный выход из задвоенного адреса звучит
        # «сдайте лишнюю из её папки». Пока каноничный ключ шёл первым, этот совет был не просто
        # неисполним, а ВРЕДЕН: человек вставал в папку призрака, сдача разрешала её в корень дерева
        # и закрывала ЖИВУЮ запись, оставив призрака открытым, — и рапортовала об успехе.
        # (Воспроизведено проверяющим на живой сцене.)
        #
        # Совпадение только ТОЧНОЕ — ни «начинается с», ни «лежит внутри»: иначе вкладка забрала бы
        # заявку соседнего дерева, вложенного в её папку. Ничего не ломает и там, где вкладка стоит
        # в корне: у её собственной записи папка и есть корень, обе дороги ведут к одной записи.
        $exact = Find-ClaimByWorktree -Claims $all -Paths @($PWD.Path)
        if ($exact) {
            $claim = $exact.Record
            $claimPath = $exact.File
        } elseif ($mine) {
            $claim = $mine
        } else {
            # Третья дорога — по точному совпадению с КОРНЕМ дерева. Так находятся заявки, поданные
            # прежней версией из подкаталога: их имя файла выведено из той папки, и по каноничному
            # ключу они не ищутся. Пишем потом обратно в НАЙДЕННЫЙ файл: заявка остаётся там, где
            # лежала, ни один файл не заводится и не удаляется.
            $found = Find-ClaimByWorktree -Claims $all -Paths @($tree)
            if ($found) {
                $claim = $found.Record
                $claimPath = $found.File
            }
        }
        if (-not $claim) {
            'Заявки на этой вкладке нет — сдавать нечего. Объявиться: -Mode Claim (волну и номер потока можно не называть).'
            return
        }
        if ([string]$claim.state -eq 'released') {
            # Папку называем и здесь: ответ «уже сдан» про ЧУЖУЮ запись человек иначе примет за свою.
            "Поток $($claim.wave)/$($claim.stream) уже сдан ($(Format-Stamp -Raw $claim.released_at)), рабочая папка $($claim.worktree)."
            return
        }
        # ‼️ Адрес у этой вкладки ЗАБРАЛИ. Состояние это живёт только в разобранном реестре — в
        # своём файле запись выглядит открытой, — и, не спроси мы реестр, сдача закрыла бы запись,
        # которой уже никто не адресует, и отрапортовала бы «поток сдан, находки ему больше не
        # примут» про поток, который в этот момент ведёт другая папка. Говорим правду: перенесён.
        $myEntry = Get-ClaimEntry -Claims $all -Claim $claim -Path $claimPath
        if ($myEntry -and $myEntry.Superseded) {
            # ‼️ «Адрес ведёт та вкладка» верно только тогда, когда забравшая папка и вправду ведёт
            # ТОТ ЖЕ адрес. Она могла с тех пор сдаться или взяться за следующий поток — тогда
            # ведущей записи у адреса не осталось вовсе, и посылать человека туда нельзя.
            $fate = Get-ClaimAddressFate -Claim $myEntry
            if ($fate.StillLed) {
                "Поток $($claim.wave)/$($claim.stream) $($fate.Text) — сдавать здесь нечего: адрес ведёт та вкладка."
                'Эта вкладка больше не адресуема: находки по адресу приходят туда, и закрывать их отсюда нельзя.'
                # ‼️ Ключ переноса советуем только там, где ему есть у кого забрать адрес: без
                # ведущей записи он ответит «не понадобился», и напечатанный выход окажется пустым.
                "Это ваш поток и переносили его по ошибке — верните адрес себе: pwsh scripts/wave-board.ps1 -Mode Claim -Wave $($claim.wave) -Stream $($claim.stream) -TakeOver"
            } else {
                "Поток $($claim.wave)/$($claim.stream) здесь больше не ведут: $($fate.Text) — сдавать нечего."
                'Ведущей записи у адреса не осталось: находку по нему приём не примет, а эта вкладка снаружи не адресуема.'
                'Забрать адрес обратно нечем — забравшая папка ушла дальше или закончила поток. Новая работа — объявитесь свободным номером: pwsh scripts/wave-board.ps1 -Mode Claim'
            }
            return
        }
        $content = Read-BoardContent -Path $board
        if (-not $content.Ok) {
            Deny-Call "доску не удалось прочитать ($board), а сдавать поток вслепую нельзя. Последняя причина: $($content.Reason)"
        }
        # Реестр читаем ОДИН раз, и из него берём и то, и другое.
        #
        # ‼️ Имена волн нужны разбору адреса «волна/поток», когда волна названа СЛОВОМ: на старте
        # инструмента список строится терпимо, и одна занятая заявка лишала слово права быть именем
        # волны — тогда находка не считалась находкой этого потока, ящик выглядел пустым, и сдача
        # ПРОХОДИЛА успехом, оставляя запись на доске навсегда.
        #
        # ‼️ Имена потока — тем же единственным набором, каким приём решает, кому находка
        # адресована, а сторож доставки — моя ли это запись. Разъедься они, и находка, принятая по
        # одному имени, не нашлась бы по другому.
        $registryNow = @(Get-Claims -Dir $registry -Strict)
        Set-KnownWaves -Keys @($registryNow | ForEach-Object { $_.WaveKey })
        $keys = @(Get-StreamNames -Claim $claim -Claims $registryNow)
        $records = @(Select-OpenEntries -Entries (Get-BoardEntries -Lines $content.Lines) -Viewer $keys |
                ForEach-Object { $_.Record })
        # Уведомления «учтено» из ящика исключаем: они гаснут сами при показе, и требовать их
        # закрытия перед сдачей — значит отклонять сдачу из-за записи, которая работы не несёт.
        $left = @(Select-ForStream -Records $records -Keys $keys -Claim $claim |
                Where-Object { [string]$_.kind -ne 'ack' })
        # Есть ли у потока план волны. Без плана вписывать итог и оставшиеся находки некуда, и
        # советовать раздел несуществующего файла — тупик: вкладка не может ни выполнить совет, ни
        # понять, что делать вместо него.
        $hasPlan = Test-ClaimHasPlan -Claim $claim
        if ($left.Count -gt 0 -and -not $Force) {
            $list = @($left | ForEach-Object { Format-BoardRecord -Record $_ }) -join "`n"
            $notMine = if ($hasPlan) {
                'Не ваша работа — перенесите пунктом в раздел «Хвосты волны» плана, закройте и сдайте поток: -Mode Release -Force'
            } else {
                'Не ваша работа — назовите её в ответе владельцу и сдайте поток ключом -Force.'
            }
            Deny-Call @"
в ящике потока $($claim.wave)/$($claim.stream) осталось открытым: $($left.Count) — сдать поток нельзя, иначе они не достанутся никому.
$list
Учли — закройте каждую: -Mode Done -Id <метка>.
$notMine
"@
        }
        $claim.state = 'released'
        $claim | Add-Member -NotePropertyName released_at -NotePropertyValue ((Get-Date).ToString('s')) -Force
        Write-ClaimFile -Path $claimPath -Claim $claim
        # ‼️ Говорим, ЧТО именно закрыли: адрес, имя и рабочую папку записи. Дорог к своей заявке у
        # сдачи три, и человек не обязан помнить, какая сработала; пока печатался один адрес,
        # подмена записи была ему не видна вовсе — а именно так проверяющий и получил сданной живую
        # запись вместо призрака, с бодрым рапортом об успехе.
        $closedName = if ($claim.name) { "«$($claim.name)»" } else { 'без имени' }
        $closedFolder = if ($claim.worktree) { [string]$claim.worktree } else { 'в заявке не названа' }
        "Закрыта заявка $($claim.wave)/$($claim.stream) $closedName, рабочая папка $closedFolder."
        if ($hasPlan) {
            "Поток $($claim.wave)/$($claim.stream) сдан. Находки ему больше не примут — их место в «Хвостах волны»."
        } else {
            "Поток $($claim.wave)/$($claim.stream) сдан. Находки ему больше не примут."
        }
        if ($left.Count -gt 0) {
            if ($hasPlan) {
                "‼️ Сдано с непустым ящиком: осталось записей $($left.Count) — они не достанутся никому, перенесите их в «Хвосты волны»."
            } else {
                "‼️ Сдано с непустым ящиком: осталось записей $($left.Count) — они не достанутся никому, назовите их в ответе владельцу."
            }
            foreach ($record in $left) { Format-BoardRecord -Record $record }
        }
        if ($hasPlan) {
            'Последнее действие — строка своего потока в разделе «Состояние потоков» плана волны.'
        } else {
            'Плана волны нет — строку потока вписывать некуда, итог идёт в ответ владельцу.'
        }
    }

    'Streams' {
        # Кто какой поток ведёт. Отвечает и на вопрос «чей это кусок работы»: -Task <номер>.
        #
        # ‼️ Строго. Это тот самый вопрос, который правила велят задать ПЕРЕД тем, как предлагать
        # владельцу работу за пределами своих задач. Пропусти он заявку соседа — и ответ звучит
        # «задачу никто не взял», то есть прямым разрешением занять чужой кусок; владелец
        # подтвердит, потому что знать не может. Цена — две вкладки делают одну работу и сводят её
        # конфликтом слияния. Команда редкая и по прямой просьбе человека, ждать секунду ей не
        # жалко (воспроизведено: при занятом файле заявки соседа ответ был именно «никто не взял»).
        $claims = @(Get-Claims -Dir $registry -Strict)
        if ($Wave) {
            $waveKey = Get-WaveKey -Raw $Wave
            $claims = @($claims | Where-Object { $_.WaveKey -eq $waveKey })
        }
        # Задвоенный адрес ищем ДО отбора по задаче, но после отбора по волне: отбор по задаче
        # оставляет одну строку из двух, и задвоение стало бы невидимым ровно в том вопросе, ради
        # которого его и надо знать, — «чей это кусок работы».
        $doubled = @(Get-DoubledAddresses -Claims $claims)
        # ‼️ И обратная беда того же рода: у адреса есть незакрытые в своих файлах записи, а ведущей
        # — ни одной. Так выглядит вкладка, которой снаружи не существует: её файл заявки открыт,
        # она считает, что ведёт поток, а находку по этому адресу приём не примет и сторож доставки
        # не принесёт. Само по себе это законный конец истории адреса (поток переехал и там
        # закончился), но выбор «жива ли эта вкладка» человек делать не может, пока молчат.
        $leaderless = @(Get-LeaderlessAddresses -Claims $claims)
        if ($Task) {
            $claims = @($claims | Where-Object { Test-TaskInList -Tasks ([string]$_.Record.tasks) -Task $Task })
        }
        # ‼️ Задвоенный адрес — отдельной громкой строкой, а не двумя похожими строками в списке.
        # Пока об этом молчат, выбор «какую из двух записей считать настоящей» делает порядок описи
        # каталога, а не человек: находка уходит одной из них молча, и половина адресованного
        # пропадает с бодрым рапортом об успехе.
        #
        # ‼️ Печатается ДО любого раннего возврата. Считалась строка и раньше до отбора по задаче, а
        # печаталась после — и пропадала ровно в самом опасном ответе: «задачу никто не взял» читают
        # как разрешение занять кусок, а он в этот момент может вестись сразу двумя записями.
        foreach ($pair in $doubled) {
            $folders = @($pair.Claims | ForEach-Object { [string]$_.Record.worktree }) -join ' и '
            "‼️ Адрес $($pair.Address) ведут сразу несколько незакрытых записей ($($pair.Claims.Count)): папки $folders."
            '   Кому из них придёт находка, решает порядок описи каталога — разберитесь, чья вкладка ведёт поток на самом деле, и сдайте лишнюю, встав ровно в её папку.'
        }
        foreach ($pair in $leaderless) {
            $folders = @($pair.Claims | ForEach-Object { [string]$_.Record.worktree }) -join ' и '
            "‼️ У адреса $($pair.Address) ведущей записи не осталось, а незакрытые заявки есть: папки $folders."
            '   Находку по этому адресу приём не примет: поток уехал и там закончился. Вкладки в этих папках снаружи не адресуемы — им надо объявиться заново или забрать адрес обратно ключом переноса.'
        }
        if ($claims.Count -eq 0) {
            if ($Task) {
                "Задача $Task не объявлена ни одним потоком — либо её никто не взял, либо поток не назвал свои задачи при объявлении."
                return
            }
            "Заявок на потоки нет ($registry)."
            return
        }
        "Заявок на потоки: $($claims.Count)"
        foreach ($claim in $claims) { Format-ClaimLine -Claim $claim }
        ''
        '«ведёт» — вкладка отмечалась в последние часы; «молчит» — могла закрыться без сдачи, а могла работать молча.'
    }

    'Add' {
        if (-not $To) {
            Deny-Call 'нужен -To: номер потока в волне (wave6/3), ветка или рабочая папка потока, * — своей волне, ** — всему проекту'
        }
        $wanted = Get-StreamKey -Raw $To
        # ‼️ Строго и ДО разбора адреса. Пропущенная заявка стоит здесь потерянной находки: поток,
        # который на самом деле СДАН, выглядит «ещё не объявлявшимся», запись принимается с
        # рапортом «дождётся его заявки» — а заявки не будет никогда. Автор после такого рапорта
        # успокаивается и запасного пункта в плане не заводит (воспроизведено).
        $claims = @(Get-Claims -Dir $registry -Strict)
        # Имена волн разбору адреса даём из ЭТОГО снимка, а не из отдельного терпимого чтения:
        # иначе адрес волны-даты мог не разобраться из-за заявки, которую то чтение пропустило.
        Set-KnownWaves -Keys @($claims | ForEach-Object { $_.WaveKey })
        $address = Get-StreamAddress -Raw $To
        Assert-Addressee -Raw $To -Address $address -Claims $claims
        $clean = ($Title -replace '\s+', ' ').Trim()
        # Пустой заголовок и заголовок из одних пробелов — одно и то же: такую запись не увидит
        # никто (показ её прячет, доставка пропускает), а рапорт был бы бодрым.
        if (-not $clean) { Deny-Call 'нужен -Title: заголовок в одну строку, из одних пробелов не годится' }
        if ($clean.Length -gt $MaxTitleLength) {
            $clean = $clean.Substring(0, $MaxTitleLength - 1) + '…'
            Write-Warning "заголовок обрезан до $MaxTitleLength знаков — на доске крючок, полный текст в плане или задаче"
        }
        # Автора заполняем ВСЕГДА: по нему отсеивается собственная запись, адресованная всем. Пустое
        # поле возвращало бы такую находку автору же — а имя рабочей папки известно и без git.
        # Имя папки — у КОРНЯ дерева: из подкаталога вкладка назвалась бы именем подкаталога, не
        # узнала бы в нём себя и получила бы собственную запись «всем» обратно.
        $from = ((Get-TreeRoot) -split '/')[-1]
        try {
            $branch = (& git rev-parse --abbrev-ref HEAD 2>$null)
            if ($LASTEXITCODE -eq 0 -and $branch) { $from = $branch.Trim() }
        } catch {
            # Ветку узнать не вышло — остаётся имя папки, для отсева этого достаточно.
        }
        # Волну не назвали — берём из своей заявки. Так запись «всем» сама собой оказывается
        # адресованной СВОЕЙ волне, а не всем двум десяткам деревьев проекта.
        # Строго: из своей заявки берётся волна записи, а по ней решается, кому уйдёт находка
        # «всем» — своей волне или всем двум десяткам деревьев проекта.
        $mine = Get-CurrentClaim -Dir $registry -Strict
        $waveOfRecord = $Wave
        if (-not $waveOfRecord -and $mine) { $waveOfRecord = [string]$mine.wave }
        $record = [ordered]@{
            id    = [guid]::NewGuid().ToString('N').Substring(0, 8)
            at    = (Get-Date).ToString('s')
            wave  = $waveOfRecord
            to    = $To
            title = $clean
            where = $Where
            from  = $from
        }
        Add-BoardLine -Path $board -Line ($record | ConvertTo-Json -Depth 3 -Compress)
        # Рапорт говорит ровно то, что знает, и в обе стороны. Свежая отметка значит «вкладка
        # работала недавно», а не «работает сейчас»: закрыться она могла и час назад, снимать
        # отметку при закрытии некому. Обещать доставку твёрдо нельзя — автор находки на этом
        # успокоится и не заведёт ей задание в «Хвостах волны». Нет отметки — это тоже не
        # «закрыта», а «неизвестно»: находка в любом случае лежит и ждёт.
        $addressed = @(Find-Claims -Claims $claims -Raw $To | Where-Object { -not $_.Closed })
        $fate = if ($wanted -eq '**') {
            'Дойдёт до всех вкладок проекта, кроме этой, — включая заведённые под другие волны.'
        } elseif ($wanted -eq '*') {
            if ($waveOfRecord) {
                "Дойдёт до вкладок волны $waveOfRecord, отмечавшихся недавно, кроме этой."
            } else {
                'Волна не названа и заявки у вас нет — дойдёт до всех вкладок проекта, кроме этой.'
            }
        } elseif ($addressed.Count -gt 0 -and $addressed[0].State -eq 'ведёт') {
            "Поток ведёт вкладка (отметка $(Format-Stamp -Raw $addressed[0].Record.seen_at)) — скорее всего, дойдёт сама."
        } elseif ($addressed.Count -gt 0) {
            # Куда дублировать — через ту же общую проверку, что и все остальные советы: заявка
            # получателя уже найдена, и «Хвосты волны» в проекте без плана были бы указанием в
            # пустоту, а находка после него не попадала бы никуда вовсе.
            $spare = if (Test-AddresseeHasPlan -Claims $claims -Raw $To -Address $address -Mine $mine) {
                'Продублируйте находку пунктом в «Хвостах волны».'
            } else {
                'Назовите находку в ответе владельцу.'
            }
            "Поток объявлен, но вкладка давно не отмечалась — жива она или нет, неизвестно. $spare"
        } elseif ($address) {
            # Адрес «волна/поток» доходит ТОЛЬКО через заявку: имени ветки в нём нет, и совпасть
            # ему не с чем, пока поток не объявился. Это не потеря — запись лежит и ждёт.
            'Поток ещё не объявлялся — запись дождётся его заявки и придёт в первую же минуту работы.'
        } elseif ($wanted -in (Get-KnownStreamKeys -AliveOnly)) {
            # Адрес по имени ветки или папки доходит и без заявки — по ключу дерева. Поэтому здесь
            # говорим ровно то же, что говорили до реестра: отметка означает «работала недавно».
            'Вкладка соседа отмечалась недавно — скорее всего, дойдёт сама.'
        } else {
            'Свежей отметки у вкладки соседа нет — жива она сейчас или нет, неизвестно; находка её дождётся.'
        }
        "Положено на доску волны для «$To» (метка $($record.id)). $fate"
        # ‼️ Задвоенный адрес — громкой строкой и в приёме, а не только в показе. Успокаивает автора
        # находки именно приём: после бодрого «скорее всего, дойдёт сама» он не заводит ей запасного
        # пункта в «Хвостах волны», а достаться она может не тому — кому именно, решает порядок
        # описи каталога. Молчать об этом дороже всего как раз здесь.
        if ($addressed.Count -gt 1 -and $wanted -notin @('*', '**')) {
            $rivalFolders = @($addressed | ForEach-Object { [string]$_.Record.worktree }) -join ' и '
            "‼️ Адрес «$To» ведут сразу $($addressed.Count) незакрытых записей: папки $rivalFolders — находка может достаться не тому."
            '   Разберитесь, чья вкладка ведёт поток на самом деле, и сдайте лишнюю, встав ровно в её папку: -Mode Streams'
        }
        # Уплотняем сами, когда доска разрослась: разбирают её целиком на каждом ходу каждой
        # вкладки, а просьба «уплотните руками» адресована тому, кто пришёл сюда за другим. Работа
        # безопасная — она отказывается при любом сомнении, — и её отказ не должен ронять добавление
        # находки: запись уже легла, и это главное.
        try {
            $lines = @((Read-BoardContent -Path $board).Lines)
            if ($lines.Count -gt $CrowdedLines) {
                $squeezed = Compress-Board -Path $board
                if ($squeezed.Before -gt $squeezed.After) {
                    "Доска попутно уплотнена: было строк $($squeezed.Before), осталось $($squeezed.After)."
                }
            }
        } catch {
            "Доска разрослась, но уплотнить её не удалось: $($_.Exception.Message)"
        }
    }

    'Done' {
        if (-not $Id) { Deny-Call 'нужен -Id: метка записи, которую закрываем (её видно в показе доски)' }
        $content = Read-BoardContent -Path $board
        if (-not $content.Ok) {
            # Занятая доска — это не «записи нет»: раньше сбой чтения выглядел как «возможно, её уже
            # закрыли», и человек уходил успокоенным, ничего не закрыв.
            Deny-Call "доску не удалось прочитать ($board). Последняя причина: $($content.Reason)"
        }
        $entries = Get-BoardEntries -Lines $content.Lines
        $mineKeys = @(Get-CurrentKeys)
        # Ищем запись глазами своего потока — кроме случая «снять у всех»: тот, кто учёл находку
        # персонально, первым и понимает, что тема исчерпана, а его собственное закрытие прячет её
        # от него самого. Без этого исключения единственный выход с доски был бы заперт перед ним.
        $lookupKeys = if ($ForAll) { @() } else { $mineKeys }
        $record = @(
            Select-OpenEntries -Entries $entries -Viewer $lookupKeys |
                Where-Object { [string]$_.Record.id -eq $Id } |
                ForEach-Object { $_.Record }
        )[0]
        if (-not $record) {
            # Отвечаем тем, что есть на самом деле. Общий ответ «закрыли у всех или просрочена» врал
            # чаще всего именно тому, кто минуту назад закрыл запись у себя: ни того, ни другого не
            # случилось, а выход (снять у всех) остался неназванным.
            $states = Get-BoardStates -Entries $entries -Viewer $mineKeys
            $isMine = @($states.ClosedForViewer | Where-Object { [string]$_.Record.id -eq $Id }).Count -gt 0
            $isStale = @($states.Stale | Where-Object { [string]$_.Record.id -eq $Id }).Count -gt 0
            $isBroken = @($states.Broken | Where-Object { [string]$_.Record.id -eq $Id }).Count -gt 0
            if ($isMine) {
                "Запись «$Id» вы уже закрыли у себя — соседям она по-прежнему видна."
                "Тема исчерпана и им не нужна — снять у всех: pwsh scripts/wave-board.ps1 -Mode Done -Id $Id -ForAll"
            } elseif ($isStale) {
                "Запись «$Id» просрочена (старше $(Get-BroadcastLifetimeDays) дней) — она уже сошла с доски."
            } elseif ($isBroken) {
                "У записи «$Id» испорчено поле времени — она снята с доставки; поправьте дату в файле доски."
            } else {
                "Записи «$Id» среди открытых нет — её закрыли у всех либо такой метки на доске не было."
            }
            return
        }
        # ‼️ Закрыть находку с ИМЕННЫМ адресом может только тот, кому она адресована. Такое
        # закрытие ОБЩЕЕ — кто закрыл первым, погасил её у всех, — и потому чужая рука здесь стоит
        # находки целиком: истинный адресат не увидит её ни в доставке, ни на доске, сдастся
        # зелёным с пустым ящиком, а автору придёт «учтено» от потока, которого он не называл.
        #
        # Сегодня доставка носит такую находку ровно одному потоку, так что чужой её метки просто
        # неоткуда узнать. Но проверка стоит второй дверью: узнают — не закроют, а услышат, чья
        # это запись. Осознанный выход остаётся ключом -ForAll: тема исчерпана и адресату не нужна.
        $addressedToMe = $ForAll -or (Get-StreamKey -Raw ([string]$record.to)) -in @('*', '**')
        if (-not $addressedToMe) {
            $registryNow = @(Get-Claims -Dir $registry -Strict)
            Set-KnownWaves -Keys @($registryNow | ForEach-Object { $_.WaveKey })
            $myClaim = Get-CurrentClaim -Dir $registry -Strict
            $myClaimPath = ''
            if (-not $myClaim) {
                # ‼️ Вторая дорога к своей заявке — та же, какой уже пользуются сдача и сторож
                # доставки: по ТОЧНОМУ совпадению записанной в заявке рабочей папки. Заявки,
                # поданные прежней версией из подкаталога, лежат под ключом того подкаталога и по
                # каноничному ключу не находятся вовсе.
                #
                # Без неё проверка закрытости не срабатывала совсем, и вкладка, у которой ЗАБРАЛИ
                # адрес, гасила находку нового владельца: закрытие именного адреса ОБЩЕЕ, так что
                # он не увидел бы её ни в доставке, ни на доске, а её автору пришло бы «учтено».
                #
                # Это ЧТЕНИЕ: ни один файл не заводится, не удаляется и не переименовывается.
                $found = Find-ClaimByWorktree -Claims $registryNow -Paths @((Get-TreeRoot), $PWD.Path)
                if ($found) {
                    $myClaim = $found.Record
                    $myClaimPath = $found.File
                }
            }
            $myNames = @(Get-StreamNames -Claim $myClaim -Claims $registryNow)
            # ‼️ ЗАКРЫТАЯ запись не закрывает находок вовсе — ни сданная, ни перенесённая. Своё
            # состояние спрашиваем у реестра, а не у своего файла: перенос в файле не отражён, и
            # вкладка, у которой адрес забрали, гасила бы находки нового владельца — закрытие
            # именного адреса ОБЩЕЕ, так что он не увидел бы их ни в доставке, ни на доске, а автору
            # пришло бы «учтено» от потока, которого он не называл.
            #
            # ‼️ Условие начинается с «заявка ЕСТЬ». Вкладка, которая не объявлялась вовсе, закрывает
            # адресованное ей по имени ветки или папки — это запасной путь, и он работал до реестра;
            # обнули мы имена и ей, единственный выход с доски оказался бы заперт перед каждой
            # необъявившейся вкладкой.
            if ($myClaim -and (Test-ClaimClosed -Claims $registryNow -Claim $myClaim -Path $myClaimPath)) {
                $myClaim = $null
                $myNames = @()
            }
            $addressedToMe = @(Select-ForStream -Records @($record) -Keys $myNames -Claim $myClaim).Count -gt 0
        }
        if (-not $addressedToMe) {
            Deny-Call @"
запись «$Id» адресована не вам, а потоку «$($record.to)» — закрытие такой записи ОБЩЕЕ, и вы погасили бы её у него.
Он её тогда не увидит ни в доставке, ни на доске, а её автору придёт «учтено» от вас.
Тема исчерпана и адресату не нужна — снять у всех осознанно: pwsh scripts/wave-board.ps1 -Mode Done -Id $Id -ForAll
"@
        }
        $closing = [ordered]@{ id = $Id; at = (Get-Date).ToString('s'); done = $true }
        # Широковещательных адресов ДВА: «всем своей волны» и «всем вкладкам проекта». Забыть
        # второй — значит погасить запись у всех разом первым же учтившим её потоком.
        $broadcast = (Get-StreamKey -Raw ([string]$record.to)) -in @('*', '**')
        # Находку «всем» каждый адресат учитывает сам за себя, поэтому её закрытие несёт ключ
        # закрывшего и гасит запись только у него. Общий выход тоже нужен: без него запись не убрать
        # с доски вовсе — она будет приходить каждому НОВОМУ дереву, даже не из этой волны.
        if ($broadcast -and -not $ForAll) {
            if ($mineKeys.Count -eq 0) {
                Deny-Call 'не удалось определить, чей это поток, а закрытие записи «всем» — именное; снять её у всех сразу: -ForAll'
            }
            $closing.by = $mineKeys[0]
        }
        Add-BoardLine -Path $board -Line ($closing | ConvertTo-Json -Depth 2 -Compress)
        # Автору находки говорим, что её учли. Без этого он не узнаёт её судьбу никогда, а от неё
        # зависит, заводить ли ей задание в «Хвостах волны». Уведомление адресовано автору, помечено
        # особым видом и закрывается само при показе — новой работы оно не создаёт.
        # Записи «всем» не подтверждаем: у неё адресатов много, и автор получил бы столько же
        # уведомлений об одном и том же. Подтверждение имеет смысл там, где адресат один и исход
        # у находки определённый.
        $author = Get-StreamKey -Raw ([string]$record.from)
        if ($author -and -not $broadcast -and $author -notin $mineKeys -and [string]$record.kind -ne 'ack') {
            $ack = [ordered]@{
                id    = [guid]::NewGuid().ToString('N').Substring(0, 8)
                at    = (Get-Date).ToString('s')
                wave  = [string]$record.wave
                to    = [string]$record.from
                title = "учтено: «$($record.title)»"
                where = "закрыл поток $(if ($mineKeys.Count -gt 0) { $mineKeys[0] } else { 'неизвестный' })"
                from  = if ($mineKeys.Count -gt 0) { $mineKeys[0] } else { '' }
                kind  = 'ack'
            }
            Add-BoardLine -Path $board -Line ($ack | ConvertTo-Json -Depth 3 -Compress)
        }
        if ($broadcast -and $ForAll) {
            "Запись «$Id» закрыта для всех адресатов — тема исчерпана, соседям она больше не придёт."
        } elseif ($broadcast) {
            "Запись «$Id» закрыта для потока «$($mineKeys[0])» — остальным адресатам она по-прежнему видна."
            "Тема исчерпана и соседям не нужна — снять у всех: pwsh scripts/wave-board.ps1 -Mode Done -Id $Id -ForAll"
        } else {
            "Запись «$Id» закрыта — больше вкладкам не показывается."
        }
    }

    'Compact' {
        $result = Compress-Board -Path $board
        if ($result.Before -eq 0) {
            "Уплотнять нечего — на доске нет ни строки ($board)."
            return
        }
        "Доска уплотнена: было строк $($result.Before), осталось $($result.After) (только открытые записи)."
        if ($result.Unreadable -gt 0) {
            # Обрывок записи — это чья-то находка, которую не разобрать. Стёртое молча неотличимо
            # от того, чего не было, поэтому о выброшенном говорим вслух.
            "Не разобрано и выброшено строк: $($result.Unreadable) — это обрывки записей."
        }
    }

    'Show' {
        $content = Read-BoardContent -Path $board
        if (-not $content.Ok) {
            Deny-Call "доску не удалось прочитать ($board). Последняя причина: $($content.Reason)"
        }
        $entries = Get-BoardEntries -Lines $content.Lines
        # Смотрим глазами названного потока: у него могут быть свои закрытия. Ключей у потока два —
        # по ветке и по папке, и они могут свестись к РАЗНЫМ; берём оба, иначе показ не узнает
        # собственное закрытие этого потока и покажет учтённую находку как открытую.
        $viewer = if ($To) { @(Get-StreamKeys -Raw $To) } else { @() }
        $states = Get-BoardStates -Entries $entries -Viewer $viewer
        $open = Select-Asked -Records @($states.Open | ForEach-Object { $_.Record })
        $closedHere = Select-Asked -Records @($states.ClosedForViewer | ForEach-Object { $_.Record })
        $stale = Select-Asked -Records @($states.Stale | ForEach-Object { $_.Record })
        $broken = Select-Asked -Records @($states.Broken | ForEach-Object { $_.Record })
        $total = $content.Lines.Count
        # Сколько строк уберёт уплотнение, считаем ТЕМ ЖЕ отбором, каким оно и работает: советовать
        # уплотнение, которое ничего не уберёт, — работа впустую и ложная надежда.
        $droppable = $total - @(Select-KeepEntries -Entries $entries).Count
        if ($total -gt $CrowdedLines) {
            "Доска разрослась: строк $total, из них открытых $($open.Count)."
            if ($droppable -gt 0) {
                "Уплотнение уберёт строк: $droppable — pwsh scripts/wave-board.ps1 -Mode Compact"
            } else {
                'Уплотнение ничего не уберёт — на доске только нужные строки.'
            }
            ''
        }
        # Про остальные состояния говорим вслух: молчание о них выглядит как пропажа записи.
        $aside = @()
        if ($closedHere.Count -gt 0) { $aside += "закрыто у вас — $($closedHere.Count)" }
        if ($stale.Count -gt 0) {
            $aside += "просрочено (старше $(Get-BroadcastLifetimeDays) дней) — $($stale.Count)"
        }
        $asideLine = if ($aside.Count -gt 0) { "Ещё на доске: $($aside -join ', ')." } else { $null }
        # Испорченная дата — отдельной строкой: это не «устарело само», а испорченный файл, и
        # человеку надо понять, почему находка пропала и что с ней делать.
        $brokenLine = if ($broken.Count -gt 0) {
            "Записей с испорченным полем времени: $($broken.Count) — они не доставляются; поправьте дату в файле доски или закройте их."
        } else { $null }
        if ($open.Count -eq 0) {
            "Открытых записей на доске волны нет ($board)."
            if ($asideLine) { $asideLine }
            if ($brokenLine) { $brokenLine }
            return
        }
        "Открытых записей на доске волны: $($open.Count) ($board)"
        $anyBroadcast = $false
        foreach ($record in $open) {
            $tail = if ($record.where) { " — $($record.where)" } else { '' }
            $wave = if ($record.wave) { "волна $($record.wave), " } else { '' }
            # Кто уже учёл — только про записи «всем»: у них закрытие персональное, и молчать об
            # этом значит выдавать «ещё никем не учтено» за правду.
            $seen = $states.Closings.By[[string]$record.id]
            $mark = if ($seen -and $seen.Count -gt 0) { " (учли: $($seen -join ', '))" } else { '' }
            if ((Get-StreamKey -Raw ([string]$record.to)) -eq '*') { $anyBroadcast = $true }
            "  [$($record.id)] ${wave}кому: $($record.to) — «$($record.title)»$tail$mark"
        }
        if ($asideLine) { $asideLine }
        if ($brokenLine) { $brokenLine }
        ''
        'Учли находку — закройте её: pwsh scripts/wave-board.ps1 -Mode Done -Id <метка>'
        if ($anyBroadcast) {
            'Запись «всем» гасится только у вас; тема исчерпана и соседям не нужна — добавьте -ForAll.'
        }
    }
