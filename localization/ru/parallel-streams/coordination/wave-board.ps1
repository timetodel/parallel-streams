. (Join-Path $PSScriptRoot 'lib/wave-board-lib.ps1')

# Заголовок длиннее — уже не крючок, а пересказ: полному тексту место в плане или в задаче.
$MaxTitleLength = 200

# Столько строк на доске — повод уплотнить: разбирают её целиком на каждом ходу каждой вкладки.
$CrowdedLines = 200

# Больше имён в отказе — не подсказка, а стена: похожее и так стоит первым.
$MaxHints = 8

function Deny-Call {
    param([string]$Message)
    # Отказ пишем прямо в поток ошибок и выходим кодом: `throw` завернул бы текст в рамку
    # исключения — с путём, номером строки, переносами и цветом. Читать его человеку, а не среде,
    # поэтому через рамку не идёт НИ ОДИН отказ, даже однострочный.
    [Console]::Error.WriteLine($Message)
    exit 1
}

function Get-TailsAdvice {
    param($Claims, [string]$Raw, $Address, [switch]$Closed)
    # Куда девать находку, которой некуда прийти. Развилка одна на все такие советы, и держится она
    # здесь: разъедься она по веткам — половина отказов посылала бы вкладку в раздел плана, которого
    # в проекте нет вовсе, и работа вставала бы на тупике.
    #
    # ‼️ План смотрим у ПОЛУЧАТЕЛЯ, а не у себя: свой план ничего не говорит о том, куда писать
    # находку для соседа.
    $mine = Get-CurrentClaim -Dir $registry -Strict
    if (Test-AddresseeHasPlan -Claims $Claims -Raw $Raw -Address $Address -Mine $mine) {
        if ($Closed) {
            return @'
Дерева нет вовсе (поток закрыт) — находке место в разделе «Хвосты волны» плана, отдельным пунктом
с готовым текстом запуска новой вкладки, а не на доске.
'@.Trim()
        }
        return 'Находке место в разделе «Хвосты волны» плана — отдельным пунктом с готовым текстом запуска новой вкладки.'
    }
    return 'Плана волны нет — назовите находку в ответе владельцу.'
}

function Assert-Addressee {
    param([string]$Raw, $Address, $Claims)
    # Сверка адресата. Порядок важен: сперва реестр заявок (он знает, ЖИВ ли поток и не сдан ли),
    # и только если поток не объявлялся — старая сверка со списком рабочих деревьев.
    if ($Raw -in @('*', '**')) { return }
    $found = @(Find-Claims -Claims $Claims -Raw $Raw)
    $live = @($found | Where-Object { $_.State -ne 'сдан' })
    if ($live.Count -gt 0) { return }
    if ($found.Count -gt 0) {
        # ‼️ Главная новая находка сторожа: поток СДАН. Сегодня такая запись принималась (дерево-то
        # на месте) и оставалась на доске навсегда — её некому было получить.
        $released = $found[0].Record
        $when = if ($released.released_at) { Format-Stamp -Raw $released.released_at } else { 'неизвестно когда' }
        $advice = Get-TailsAdvice -Claims $Claims -Raw $Raw -Address $Address
        Deny-Call @"
поток «$Raw» СДАН ($when) — вкладки, которая его вела, больше нет, и запись осталась бы на доске навсегда.
$advice
Кто что ведёт сейчас: pwsh scripts/wave-board.ps1 -Mode Streams
"@
    }
    if ($Address) {
        # Заявки нет вовсе: поток ещё не открывали. Это обычное дело, а не ошибка, — запись ляжет и
        # дождётся заявки. Ключ обхода тут не нужен: адрес «волна/поток» не выдумывается из имён.
        return
    }
    # ‼️ Имя, которое ПОМНЯТ двое и не носит никто, нарочно не досталось никому: иначе находка
    # ушла бы обоим, а закрытие именного адреса общее — любой погасил бы её у другого. Отказ здесь
    # обязан называть эту причину. Прежде он говорил, что адресата нет среди рабочих деревьев, и
    # предлагал три объяснения, из которых не верно ни одно, — а правда была видна только в показе
    # потоков, куда отказ и не отсылал.
    $rememberers = @(Get-NameRememberers -Claims $Claims -Name (Get-StreamKey -Raw $Raw))
    if ($rememberers.Count -gt 1) {
        $who = @($rememberers | ForEach-Object { "$($_.Record.wave)/$($_.Record.stream)" }) -join ', '
        Deny-Call @"
имя «$Raw» помнят два потока ($who), и не носит его сейчас никто — поэтому оно не досталось ни одному из них.
Находка по такому имени ушла бы обоим, а закрытие именного адреса ОБЩЕЕ: любой погасил бы её у другого.
Назовите адрес номером волны и потока — его ни с чем не спутать.
Кто как зовётся сейчас: pwsh scripts/wave-board.ps1 -Mode Streams
"@
    }
    Assert-KnownStream -Wanted (Get-StreamKey -Raw $Raw) -Raw $Raw `
        -Advice (Get-TailsAdvice -Claims $Claims -Raw $Raw -Address $Address -Closed)
}

function Assert-KnownStream {
    param([string]$Wanted, [string]$Raw, [string]$Advice)
    # Запасной путь: адресата назвали именем ветки или папки, и заявки на такой поток нет. Тогда
    # сверяем хотя бы с рабочими деревьями — иначе запись легла бы в никуда с бодрым рапортом.
    if ($Wanted -eq '*') { return }
    if (-not $Wanted) {
        Deny-Call "адресат «$Raw» сводится к пустому ключу (лишняя косая в конце?) — такую запись не получит никто"
    }
    $known = Get-KnownStreamKeys
    if ($known.Count -eq 0) {
        if ($AllowUnknownStream) { return }
        Deny-Call 'git не назвал ни одного рабочего дерева — проверить адресата нечем; осознанно кладём с -AllowUnknownStream'
    }
    if ($Wanted -in $known) { return }
    if ($AllowUnknownStream) { return }
    # Похожие имена ищем по кускам названия: чаще всего промахиваются опечаткой или чужой формой
    # имени, и правильное лежит рядом. Совсем не совпало (адресата назвали словами) — подсказываем
    # теми, кто недавно отмечался: из двух десятков деревьев эти точно живы.
    $tokens = @(($Wanted -split '[^\p{L}\p{Nd}]+') | Where-Object { $_.Length -ge 3 })
    $similar = @($known | Where-Object { $name = $_; @($tokens | Where-Object { $name -like "*$_*" }).Count -gt 0 })
    $what = 'Похожие имена'
    if ($similar.Count -eq 0) {
        $what = 'Вкладки, отмечавшиеся недавно'
        $similar = @(Get-KnownStreamKeys -AliveOnly | Sort-Object)
    }
    if ($similar.Count -eq 0) {
        $what = 'Заведённые деревья'
        $similar = @($known | Sort-Object)
    }
    $hint = @($similar | Select-Object -First $MaxHints) -join ', '
    if ($similar.Count -gt $MaxHints) { $hint += ", … и ещё $($similar.Count - $MaxHints)" }
    Deny-Call @"
адресата «$Raw» среди рабочих деревьев нет — запись легла бы в никуда, а рапорт был бы бодрым.
${what}: $hint
$Advice
Дерево ещё не заведено — повторите с -AllowUnknownStream.
"@
}

# Всё, что сорвалось глубже (доску держит антивирус, кончилось место, нет прав), выходит наружу
# обычным текстом с настоящей причиной, а не рамкой исключения с путём и номером строки: читает
# это человек, и по причине он решает, что делать дальше.
function Select-Asked {
    param($Records)
    # Один и тот же отбор на список открытых и на счёт остальных состояний. Разъедься они — строка
    # «просрочено — N» считала бы чужие волны, а список рядом с ней показывал бы только свою.
    $result = @($Records)
    if ($To) {
        $wanted = Get-StreamKey -Raw $To
        # Адрес «волна/поток» сравниваем разобранным, а не ключом: ключом `wave6/3` и `wave7/3`
        # сводятся к одной тройке, и показ выдал бы чужую волну за свою.
        $wantedAddress = Get-StreamAddress -Raw $To
        # Записи «всем» проходят отбор по потоку: доставка принесёт их в эту же вкладку.
        $result = @($result | Where-Object {
                $to = Get-StreamKey -Raw ([string]$_.to)
                if ($to -in @('*', '**')) { return $true }
                $address = Get-StreamAddress -Raw ([string]$_.to)
                if ($wantedAddress -and $address) {
                    return ($address.Wave -eq $wantedAddress.Wave -and $address.Stream -eq $wantedAddress.Stream)
                }
                if ($wantedAddress -or $address) { return $false }
                return ($to -eq $wanted)
            })
    }
    if ($Wave) { $result = @($result | Where-Object { [string]$_.wave -eq $Wave }) }
    return @($result)
}

