$board = Get-BoardPath -Override $BoardPath
$registry = Get-RegistryDir -BoardOverride $BoardPath
# Имена волн из реестра — разбору адреса. Волна зовётся не только «wave6»: там, где волн нет, её
# подставляет заявка, и зовут её датой или словом. Не назови их — адрес `2026-08-24/3` не разобрался
# бы, и находка соседу не ушла бы вовсе.
Set-KnownWavesFromRegistry -Dir $registry

switch ($Mode) {
    'Path' {
        $board
    }

    'Claim' {
        # Объявление потока. Первое действие вкладки после того, как заведено рабочее дерево: без
        # него поток снаружи неотличим от «ещё не открывали», а находки ему адресуют по имени
        # ветки, которое к этому моменту уже другое.
        $branch = ''
        try {
            $head = (& git rev-parse --abbrev-ref HEAD 2>$null)
            if ($LASTEXITCODE -eq 0 -and $head) { $branch = $head.Trim() }
        } catch {
            # Открепление от ветки: заявке хватит пути рабочего дерева.
        }
        $tree = ($PWD.Path -replace '\\', '/').TrimEnd('/')
        # ‼️ Отсюда и до конца разрешения спора — под замком реестра заявок. Выбор номера идёт по
        # снимку реестра, и без замка вкладки, открытые разом, читают ОДИН И ТОТ ЖЕ снимок: номер у
        # всех выходит одинаковый, а круг разрешения спора ниже добивает не всё — из него выходят по
        # снимку, устаревшему на чужой сдвиг, и два потока остаются с одним адресом молча, с бодрым
        # рапортом каждый. Разбор сценария целиком — у `Enter-RegistryLock`.
        #
        # Замок снимается и при отказе внутри: `finally` в PowerShell отрабатывает и на `exit`
        # (`Deny-Call`), и на исключении, перехваченном ловушкой выше. А если вкладку убьют, не дав
        # отработать и ему, замок отпустит система: держит его открытый дескриптор, а не файл.
        $lockHandle = Enter-RegistryLock -Dir $registry
        try {
            # ‼️ Строго: этот снимок ВЫБИРАЕТ НОМЕР потока. Не увидеть соседа тут — значит выдать
            # его номер второй раз, молча и навсегда; лучше отказать вслух и попросить повторить.
            $claims = @(Get-Claims -Dir $registry -Strict)
            # Волну подставляем сами, если её не назвали: канал ставят и в проекты, где волн нет
            # вовсе, и там вкладке неоткуда взять ни номер волны, ни номер потока. Отказ на этом
            # месте был тупиком — объявиться нельзя, а без объявления поток снаружи не существует.
            #
            # Ступени сверху вниз: названная волна → волна из имени плана → идущая рядом работа →
            # новая волна по сегодняшней дате.
            $waveAuto = $false
            $waveSource = 'named'
            if ($Wave) {
                $waveKey = Get-WaveKey -Raw $Wave
            } elseif ($Plan) {
                $waveKey = Get-WaveKey -Raw $Plan
                $waveSource = 'plan'
            } else {
                $joined = Get-AutoWaveKey -Claims $claims
                if ($joined) {
                    $waveKey = $joined
                    $waveSource = 'joined'
                } else {
                    $waveKey = Get-DateWaveKey
                    $waveSource = 'date'
                }
                # ‼️ Признак нужен именно здесь: присоединяться можно ТОЛЬКО к волне, подставленной
                # самой. У названной волны номера потоков идут из плана, и занять там чужой номер
                # значит развести адресацию надвое.
                $waveAuto = $true
            }
            if (-not $waveKey) {
                # Сюда попадаем, только если волну (или план) назвали, но имя свелось к пустому: без
                # имени волны у потока нет адреса, и находки ему не доставит никто.
                $named = if ($Wave) { $Wave } else { $Plan }
                Deny-Call "волна «$named» сводится к пустому имени — назовите её словом или номером"
            }
            # Номер потока тоже необязателен: в проекте без плана его неоткуда взять, а адресу он
            # нужен всегда. Названный номер работает как раньше — он идёт из таблицы плана.
            $streamAuto = $false
            if ($Stream) {
                $streamKey = Get-StreamNumberKey -Raw $Stream
                if (-not $streamKey) { Deny-Call "номер потока «$Stream» сводится к пустому — назовите его как в плане" }
            } else {
                $streamKey = Get-NextStreamNumber -Claims $claims -WaveKey $waveKey -TreePath $tree
                $streamAuto = $true
            }
            # ‼️ Прежние имена ветки переносим в новую заявку. Объявиться можно второй раз, и
            # объявление молча переписывает заявку: переименуй вкладка ветку и объявись заново —
            # старое имя стёрлось бы отовсюду, а находка, УЖЕ ПРИНЯТАЯ по нему, не дошла бы и
            # сдачу не задержала. Держим немного: имя нужно, пока живёт волна, а не вечно.
            $former = [System.Collections.Generic.List[string]]::new()
            $before = @($claims | Where-Object {
                    (([string]$_.Record.worktree) -replace '\\', '/').TrimEnd('/') -eq $tree
                })
            if ($before.Count -gt 0) {
                $earlier = @([string]$before[0].Record.branch) + @($before[0].Record.former_branches)
                foreach ($name in $earlier) {
                    # ‼️ Ничего не вытесняем. Вытесненное имя означало бы находку, УЖЕ ПРИНЯТУЮ по
                    # нему, которая перестала доставляться и перестала держать сдачу, — то есть
                    # тихую потерю, ради предотвращения которой память и заводилась. Растёт список
                    # только от настоящих переименований ветки, а это единицы за волну.
                    if ($name -and $name -ne $branch -and $name -notin $former) { $former.Add($name) }
                }
            }
            $claim = [ordered]@{
                wave            = $waveKey
                stream          = $streamKey
                # ‼️ Признак «волна подставлена сама». По нему и только по нему соседняя вкладка
                # решает, можно ли присоединиться к этой волне. Заявки старого вида его не несут —
                # и правильно: они заводились с названной волной, где номера идут из плана.
                wave_auto       = $waveAuto
                name            = $StreamName
                tasks           = $Tasks
                plan            = $Plan
                branch          = $branch
                # Имена, под которыми поток знали раньше: находка, посланная по ним, обязана дойти.
                former_branches = @($former)
                worktree        = $tree
                claimed_at      = (Get-Date).ToString('s')
                seen_at         = (Get-Date).ToString('s')
                state           = 'open'
            }
            Write-ClaimFile -Path (Get-ClaimPath -Dir $registry -TreePath $tree) -Claim $claim
            # Круг разрешения спора за номер. Под замком соперника здесь обычно НЕ находится:
            # реестр прочитан с уже записанными заявками соседей, и выбранный номер свободен. Круг
            # оставлен на случаи, где замка нет:
            #   • замок не отдали за отведённое время (о чём вкладка говорит вслух ниже) — тогда это
            #     единственная защита от двух потоков с одним адресом;
            #   • заявка соседа появилась ПОСЛЕ нашей — например, её вернули из резервной копии или
            #     принесла вкладка версии без замка.
            #
            # Разрешается спор сдвигом СВОЕГО номера: файл заявки принадлежит только этой вкладке,
            # перезаписать его безопасно. Уступает объявившийся позже (при равном времени — чей путь
            # дерева меньше по алфавиту): порядок полный и неизменный, поэтому две вкладки не
            # сдвигаются одновременно и не меняются номерами без конца.
            $movedFrom = ''
            # ‼️ Всё, что идёт ПОСЛЕ записи своей заявки, прикрыто одинаково: строгое чтение, а
            # неудача — не отказ, а громкое предупреждение. Отказывать здесь уже нельзя — заявка
            # легла, поток объявлен, и «объявиться не вышло» было бы неправдой, да ещё и с открытой
            # заявкой в реестре. Прежде так был прикрыт только последний снимок, а круг разрешения
            # спора — нет, и помеха, начавшаяся сразу после записи, давала ровно ту неправду,
            # которой прикрытие и заводилось избегать.
            $snapshotFailed = ''
            try {
                # Заходов несколько: сдвинувшись, можно попасть на номер, который в ту же
                # секунду занял третий сосед. Порядок разрешения у всех один, поэтому заходы
                # сходятся, а не кружат.
                for ($round = 1; $round -le 5; $round++) {
                    # Тоже строго: круг спора читает тот же реестр и решает тот же вопрос.
                    $claims = @(Get-Claims -Dir $registry -Strict)
                    $rivals = @(Get-NumberRivals -Claims $claims -WaveKey $waveKey -StreamKey $streamKey -TreePath $tree)
                    if ($rivals.Count -eq 0) { break }
                    # Названный номер идёт из плана — он и есть имя потока, им адресуют находки, и
                    # двигать его нельзя. Такой спор разрешает человек, о нём инструмент и
                    # говорит ниже.
                    if (-not $streamAuto) { break }
                    if (-not (Test-YieldsStreamNumber -Mine $claim -Rivals $rivals)) { break }
                    if (-not $movedFrom) { $movedFrom = $streamKey }
                    $streamKey = Get-FreeStreamNumber -Claims $claims -WaveKey $waveKey -TreePath $tree
                    $claim.stream = $streamKey
                    Write-ClaimFile -Path (Get-ClaimPath -Dir $registry -TreePath $tree) -Claim $claim
                }
                # ‼️ Снимок для рапорта берём ПОСЛЕДНИМ и ПОД ЗАМКОМ. Последним — потому
                # что пока шёл спор за номер, сосед мог сдвинуться сам, и предупреждать о нём
                # было бы неправдой. Под замком — потому что по этому снимку печатается
                # единственная защита от двух вкладок на ОДНОМ НАЗВАННОМ номере: такой номер
                # идёт из плана, двигать его нельзя, и всё, что остаётся, — сказать человеку
                # «на этот же поток есть заявка другого дерева». Им же печатается карта
                # соседей: пустой снимок означает вкладку, уверенную, что она одна.
                $claims = @(Get-Claims -Dir $registry -Strict)
                # Имена волн для разбора адреса — из ЭТОГО снимка: ниже по нему же ищутся записи,
                # оставленные потоку впрок, а их адрес может звать волну словом.
                Set-KnownWaves -Keys @($claims | ForEach-Object { $_.WaveKey })
            } catch {
                $snapshotFailed = $_.Exception.Message
                $claims = @()
            }
        } finally {
            # Замок снимаем ВСЕГДА: иначе сорвавшаяся вкладка держала бы объявление соседей до
            # конца своей жизни.
            Exit-RegistryLock -Handle $lockHandle
        }
        $rivals = @(Get-NumberRivals -Claims $claims -WaveKey $waveKey -StreamKey $streamKey -TreePath $tree)
        "Поток $waveKey/$streamKey объявлен за этой вкладкой (ветка $branch)."
        if ($snapshotFailed) {
            "‼️ Реестр заявок для сверки с соседями прочитать не удалось: $snapshotFailed"
            '   Поток объявлен, но предупреждение о совпадении номера и карта соседей не построены — сверьте вручную: -Mode Streams'
        }
        if (-not $lockHandle) {
            # Молчать об этом нельзя: без замка номер выбирался по снимку, который сосед мог
            # обогнать, — ровно тот случай, когда два потока получают один адрес и обе стороны об
            # этом не узнают.
            "‼️ Замок реестра заявок не отдали за $(Get-RegistryLockWaitSeconds) с — номер потока выбран без него, он может совпасть с соседним."
            '   Сверьте адреса: -Mode Streams. Похоже, соседняя вкладка застряла посреди объявления.'
        }
        # Откуда взялась волна — говорим вслух. Подставленную молча вкладка выдаст владельцу за
        # названную им, а соседям назовёт адрес, которого не ждала ни одна сторона.
        switch ($waveSource) {
            'date' {
                "Волна не названа — взята по сегодняшней дате. Адрес потока для соседей: $waveKey/$streamKey."
            }
            'joined' {
                # Считаем потоки волны ПОСЛЕ присоединения, вместе со своим: вкладка спрашивает
                # «сколько нас», а не «сколько было до меня».
                $inWave = @(@($claims | Where-Object { $_.WaveKey -eq $waveKey } |
                            ForEach-Object { $_.StreamKey }) + $streamKey |
                        Where-Object { $_ } | Select-Object -Unique)
                "Волна не названа — вкладка присоединена к уже идущей работе $waveKey, в ней потоков: $($inWave.Count)."
            }
            'plan' {
                'Волна взята из имени плана.'
            }
        }
        if ($streamAuto) {
            "Номер потока не назван — выдан следующий свободный: $streamKey."
        }
        if ($movedFrom) {
            "‼️ Номером $waveKey/$movedFrom в тот же миг объявилась соседняя вкладка — ваш поток сдвинут на следующий свободный: $waveKey/$streamKey."
            '   Соседям называйте новый адрес: по старому находка уйдёт чужому потоку.'
        }
        # Номер, которым потом нельзя адресовать. Разбор адреса требует справа НОМЕР, а объявление
        # принимает в это поле любое слово: такой поток адресуют только запасным путём (именем
        # ветки), а имена к середине волны врут. Не отказываем — предупреждаем сразу, пока вкладка
        # не назвала соседям адрес, которого не существует.
        if ($Stream -and -not (Get-StreamAddress -Raw "1/$Stream")) {
            "‼️ Номером «$Stream» адресовать поток нельзя: справа от косой черты разбирается только номер (3, П3, 3b)."
            '   Назовите номер потока из плана — иначе находку соседи основным способом не пошлют.'
        }
        # Записи, оставленные потоку впрок, пока его не открывали. Сторож доставки принесёт их
        # ближайшим ходом, но сказать о них здесь стоит: заявка — тот самый момент, когда вкладка
        # узнаёт, что её уже ждали.
        $waiting = @(Select-ForStream -Records (Get-OpenRecords -Path $board -Viewer (Get-CurrentKeys)) `
                -Keys (Get-CurrentKeys) -Claim $claim)
        if ($waiting.Count -gt 0) {
            "Вас уже ждут записи на доске: $($waiting.Count) — придут ближайшим ходом."
        }
        # Чужая живая заявка на тот же поток, которая осталась и после разрешения спора (номер
        # назван, а не выдан, — двигать его нельзя). Не отказ: перехват вкладки бывает осознанным,
        # первую могли закрыть, не сдав. Но и молчать нельзя — два потока с одним номером
        # раздваивают адресацию, и половина находок уходит не туда.
        foreach ($rival in $rivals) {
            "‼️ На этот же поток есть открытая заявка другого дерева: $($rival.Record.worktree) — $($rival.State)."
            '   Два потока с одним номером раздваивают адресацию: разберитесь, чья вкладка ведёт его на самом деле.'
        }
        # Карта соседей печатается сразу, а не по запросу: вкладка узнаёт границы своей работы в
        # первую же минуту. Без неё она предлагает владельцу взять соседнюю задачу, а владелец не
        # знает, что задачу планировали другому потоку, и подтверждает.
        $neighbours = @($claims | Where-Object {
                $_.WaveKey -eq $waveKey -and ($_.Record.worktree -replace '\\', '/').TrimEnd('/') -ne $tree
            })
        if ($neighbours.Count -gt 0) {
            ''
            "Соседние потоки волны ${waveKey}:"
            foreach ($neighbour in $neighbours) { Format-ClaimLine -Claim $neighbour }
            'Работа за пределами своих задач — сперва посмотрите, чей это кусок: -Mode Streams -Task <номер>.'
        }
    }

    'Release' {
        # Сдача потока. Здесь единственный раз задаётся вопрос «всё ли до меня дошедшее учтено» —
        # без него запись, положенная за десять минут до закрытия вкладки, не достаётся никому и
        # никогда, а отправителю уже отрапортовали об успехе.
        # Строго: «заявки нет» и «файл занят» ведут отсюда в противоположные стороны, а выглядят
        # одинаково — пустотой. Своя заявка читается ПЕРВОЙ: испорчена именно она — владелец
        # должен получить отказ про СВОЙ файл с его путём, а не общий отказ про заявку соседа.
        $claim = Get-CurrentClaim -Dir $registry -Strict
        if (-not $claim) {
            # ‼️ «Заявки нет» — правда только тогда, когда реестр ЧИТАЕТСЯ. На мёртвом пути
            # (отвалился диск, пропала шара) отсутствие своего файла выглядит точно так же, и
            # вкладке говорили «сдавать нечего» кодом успеха. Поэтому сперва спрашиваем реестр
            # строго: он и отличит «заявок нет» от «посмотреть не смогли».
            $null = Get-Claims -Dir $registry -Strict
            'Заявки на этой вкладке нет — сдавать нечего. Объявиться: -Mode Claim (волну и номер потока можно не называть).'
            return
        }
        if ([string]$claim.state -eq 'released') {
            "Поток $($claim.wave)/$($claim.stream) уже сдан ($(Format-Stamp -Raw $claim.released_at))."
            return
        }
        $content = Read-BoardContent -Path $board
        if (-not $content.Ok) {
            Deny-Call "доску не удалось прочитать ($board), а сдавать поток вслепую нельзя. Последняя причина: $($content.Reason)"
        }
        # Реестр читаем ОДИН раз, и из него берём и то, и другое.
        #
        # ‼️ Имена волн нужны разбору адреса «волна/поток», когда волна названа СЛОВОМ: на старте
        # инструмента список строится терпимо, и одна занятая заявка лишала слово права быть именем
        # волны — тогда находка не считалась находкой этого потока, ящик выглядел пустым, и сдача
        # ПРОХОДИЛА успехом, оставляя запись на доске навсегда.
        #
        # ‼️ Имена потока — тем же единственным набором, каким приём решает, кому находка
        # адресована, а сторож доставки — моя ли это запись. Разъедься они, и находка, принятая по
        # одному имени, не нашлась бы по другому.
        $registryNow = @(Get-Claims -Dir $registry -Strict)
        Set-KnownWaves -Keys @($registryNow | ForEach-Object { $_.WaveKey })
        $keys = @(Get-StreamNames -Claim $claim -Claims $registryNow)
        $records = @(Select-OpenEntries -Entries (Get-BoardEntries -Lines $content.Lines) -Viewer $keys |
                ForEach-Object { $_.Record })
        # Уведомления «учтено» из ящика исключаем: они гаснут сами при показе, и требовать их
        # закрытия перед сдачей — значит отклонять сдачу из-за записи, которая работы не несёт.
        $left = @(Select-ForStream -Records $records -Keys $keys -Claim $claim |
                Where-Object { [string]$_.kind -ne 'ack' })
        # Есть ли у потока план волны. Без плана вписывать итог и оставшиеся находки некуда, и
        # советовать раздел несуществующего файла — тупик: вкладка не может ни выполнить совет, ни
        # понять, что делать вместо него.
        $hasPlan = Test-ClaimHasPlan -Claim $claim
        if ($left.Count -gt 0 -and -not $Force) {
            $list = @($left | ForEach-Object { Format-BoardRecord -Record $_ }) -join "`n"
            $notMine = if ($hasPlan) {
                'Не ваша работа — перенесите пунктом в раздел «Хвосты волны» плана, закройте и сдайте поток: -Mode Release -Force'
            } else {
                'Не ваша работа — назовите её в ответе владельцу и сдайте поток ключом -Force.'
            }
            Deny-Call @"
в ящике потока $($claim.wave)/$($claim.stream) осталось открытым: $($left.Count) — сдать поток нельзя, иначе они не достанутся никому.
$list
Учли — закройте каждую: -Mode Done -Id <метка>.
$notMine
"@
        }
        $claim.state = 'released'
        $claim | Add-Member -NotePropertyName released_at -NotePropertyValue ((Get-Date).ToString('s')) -Force
        Write-ClaimFile -Path (Get-ClaimPath -Dir $registry -TreePath $PWD.Path) -Claim $claim
        if ($hasPlan) {
            "Поток $($claim.wave)/$($claim.stream) сдан. Находки ему больше не примут — их место в «Хвостах волны»."
        } else {
            "Поток $($claim.wave)/$($claim.stream) сдан. Находки ему больше не примут."
        }
        if ($left.Count -gt 0) {
            if ($hasPlan) {
                "‼️ Сдано с непустым ящиком: осталось записей $($left.Count) — они не достанутся никому, перенесите их в «Хвосты волны»."
            } else {
                "‼️ Сдано с непустым ящиком: осталось записей $($left.Count) — они не достанутся никому, назовите их в ответе владельцу."
            }
            foreach ($record in $left) { Format-BoardRecord -Record $record }
        }
        if ($hasPlan) {
            'Последнее действие — строка своего потока в разделе «Состояние потоков» плана волны.'
        } else {
            'Плана волны нет — строку потока вписывать некуда, итог идёт в ответ владельцу.'
        }
    }

    'Streams' {
        # Кто какой поток ведёт. Отвечает и на вопрос «чей это кусок работы»: -Task <номер>.
        #
        # ‼️ Строго. Это тот самый вопрос, который правила велят задать ПЕРЕД тем, как предлагать
        # владельцу работу за пределами своих задач. Пропусти он заявку соседа — и ответ звучит
        # «задачу никто не взял», то есть прямым разрешением занять чужой кусок; владелец
        # подтвердит, потому что знать не может. Цена — две вкладки делают одну работу и сводят её
        # конфликтом слияния. Команда редкая и по прямой просьбе человека, ждать секунду ей не
        # жалко (воспроизведено: при занятом файле заявки соседа ответ был именно «никто не взял»).
        $claims = @(Get-Claims -Dir $registry -Strict)
        if ($Wave) {
            $waveKey = Get-WaveKey -Raw $Wave
            $claims = @($claims | Where-Object { $_.WaveKey -eq $waveKey })
        }
        if ($Task) {
            $claims = @($claims | Where-Object { Test-TaskInList -Tasks ([string]$_.Record.tasks) -Task $Task })
        }
        if ($claims.Count -eq 0) {
            if ($Task) {
                "Задача $Task не объявлена ни одним потоком — либо её никто не взял, либо поток не назвал свои задачи при объявлении."
                return
            }
            "Заявок на потоки нет ($registry)."
            return
        }
        "Заявок на потоки: $($claims.Count)"
        foreach ($claim in $claims) { Format-ClaimLine -Claim $claim }
        ''
        '«ведёт» — вкладка отмечалась в последние часы; «молчит» — могла закрыться без сдачи, а могла работать молча.'
    }

    'Add' {
        if (-not $To) {
            Deny-Call 'нужен -To: номер потока в волне (wave6/3), ветка или рабочая папка потока, * — своей волне, ** — всему проекту'
        }
        $wanted = Get-StreamKey -Raw $To
        # ‼️ Строго и ДО разбора адреса. Пропущенная заявка стоит здесь потерянной находки: поток,
        # который на самом деле СДАН, выглядит «ещё не объявлявшимся», запись принимается с
        # рапортом «дождётся его заявки» — а заявки не будет никогда. Автор после такого рапорта
        # успокаивается и запасного пункта в плане не заводит (воспроизведено).
        $claims = @(Get-Claims -Dir $registry -Strict)
        # Имена волн разбору адреса даём из ЭТОГО снимка, а не из отдельного терпимого чтения:
        # иначе адрес волны-даты мог не разобраться из-за заявки, которую то чтение пропустило.
        Set-KnownWaves -Keys @($claims | ForEach-Object { $_.WaveKey })
        $address = Get-StreamAddress -Raw $To
        Assert-Addressee -Raw $To -Address $address -Claims $claims
        $clean = ($Title -replace '\s+', ' ').Trim()
        # Пустой заголовок и заголовок из одних пробелов — одно и то же: такую запись не увидит
        # никто (показ её прячет, доставка пропускает), а рапорт был бы бодрым.
        if (-not $clean) { Deny-Call 'нужен -Title: заголовок в одну строку, из одних пробелов не годится' }
        if ($clean.Length -gt $MaxTitleLength) {
            $clean = $clean.Substring(0, $MaxTitleLength - 1) + '…'
            Write-Warning "заголовок обрезан до $MaxTitleLength знаков — на доске крючок, полный текст в плане или задаче"
        }
        # Автора заполняем ВСЕГДА: по нему отсеивается собственная запись, адресованная всем. Пустое
        # поле возвращало бы такую находку автору же — а имя рабочей папки известно и без git.
        $from = Split-Path -Leaf $PWD
        try {
            $branch = (& git rev-parse --abbrev-ref HEAD 2>$null)
            if ($LASTEXITCODE -eq 0 -and $branch) { $from = $branch.Trim() }
        } catch {
            # Ветку узнать не вышло — остаётся имя папки, для отсева этого достаточно.
        }
        # Волну не назвали — берём из своей заявки. Так запись «всем» сама собой оказывается
        # адресованной СВОЕЙ волне, а не всем двум десяткам деревьев проекта.
        # Строго: из своей заявки берётся волна записи, а по ней решается, кому уйдёт находка
        # «всем» — своей волне или всем двум десяткам деревьев проекта.
        $mine = Get-CurrentClaim -Dir $registry -Strict
        $waveOfRecord = $Wave
        if (-not $waveOfRecord -and $mine) { $waveOfRecord = [string]$mine.wave }
        $record = [ordered]@{
            id    = [guid]::NewGuid().ToString('N').Substring(0, 8)
            at    = (Get-Date).ToString('s')
            wave  = $waveOfRecord
            to    = $To
            title = $clean
            where = $Where
            from  = $from
        }
        Add-BoardLine -Path $board -Line ($record | ConvertTo-Json -Depth 3 -Compress)
        # Рапорт говорит ровно то, что знает, и в обе стороны. Свежая отметка значит «вкладка
        # работала недавно», а не «работает сейчас»: закрыться она могла и час назад, снимать
        # отметку при закрытии некому. Обещать доставку твёрдо нельзя — автор находки на этом
        # успокоится и не заведёт ей задание в «Хвостах волны». Нет отметки — это тоже не
        # «закрыта», а «неизвестно»: находка в любом случае лежит и ждёт.
        $addressed = @(Find-Claims -Claims $claims -Raw $To | Where-Object { $_.State -ne 'сдан' })
        $fate = if ($wanted -eq '**') {
            'Дойдёт до всех вкладок проекта, кроме этой, — включая заведённые под другие волны.'
        } elseif ($wanted -eq '*') {
            if ($waveOfRecord) {
                "Дойдёт до вкладок волны $waveOfRecord, отмечавшихся недавно, кроме этой."
            } else {
                'Волна не названа и заявки у вас нет — дойдёт до всех вкладок проекта, кроме этой.'
            }
        } elseif ($addressed.Count -gt 0 -and $addressed[0].State -eq 'ведёт') {
            "Поток ведёт вкладка (отметка $(Format-Stamp -Raw $addressed[0].Record.seen_at)) — скорее всего, дойдёт сама."
        } elseif ($addressed.Count -gt 0) {
            # Куда дублировать — через ту же общую проверку, что и все остальные советы: заявка
            # получателя уже найдена, и «Хвосты волны» в проекте без плана были бы указанием в
            # пустоту, а находка после него не попадала бы никуда вовсе.
            $spare = if (Test-AddresseeHasPlan -Claims $claims -Raw $To -Address $address -Mine $mine) {
                'Продублируйте находку пунктом в «Хвостах волны».'
            } else {
                'Назовите находку в ответе владельцу.'
            }
            "Поток объявлен, но вкладка давно не отмечалась — жива она или нет, неизвестно. $spare"
        } elseif ($address) {
            # Адрес «волна/поток» доходит ТОЛЬКО через заявку: имени ветки в нём нет, и совпасть
            # ему не с чем, пока поток не объявился. Это не потеря — запись лежит и ждёт.
            'Поток ещё не объявлялся — запись дождётся его заявки и придёт в первую же минуту работы.'
        } elseif ($wanted -in (Get-KnownStreamKeys -AliveOnly)) {
            # Адрес по имени ветки или папки доходит и без заявки — по ключу дерева. Поэтому здесь
            # говорим ровно то же, что говорили до реестра: отметка означает «работала недавно».
            'Вкладка соседа отмечалась недавно — скорее всего, дойдёт сама.'
        } else {
            'Свежей отметки у вкладки соседа нет — жива она сейчас или нет, неизвестно; находка её дождётся.'
        }
        "Положено на доску волны для «$To» (метка $($record.id)). $fate"
        # Уплотняем сами, когда доска разрослась: разбирают её целиком на каждом ходу каждой
        # вкладки, а просьба «уплотните руками» адресована тому, кто пришёл сюда за другим. Работа
        # безопасная — она отказывается при любом сомнении, — и её отказ не должен ронять добавление
        # находки: запись уже легла, и это главное.
        try {
            $lines = @((Read-BoardContent -Path $board).Lines)
            if ($lines.Count -gt $CrowdedLines) {
                $squeezed = Compress-Board -Path $board
                if ($squeezed.Before -gt $squeezed.After) {
                    "Доска попутно уплотнена: было строк $($squeezed.Before), осталось $($squeezed.After)."
                }
            }
        } catch {
            "Доска разрослась, но уплотнить её не удалось: $($_.Exception.Message)"
        }
    }

    'Done' {
        if (-not $Id) { Deny-Call 'нужен -Id: метка записи, которую закрываем (её видно в показе доски)' }
        $content = Read-BoardContent -Path $board
        if (-not $content.Ok) {
            # Занятая доска — это не «записи нет»: раньше сбой чтения выглядел как «возможно, её уже
            # закрыли», и человек уходил успокоенным, ничего не закрыв.
            Deny-Call "доску не удалось прочитать ($board). Последняя причина: $($content.Reason)"
        }
        $entries = Get-BoardEntries -Lines $content.Lines
        $mineKeys = @(Get-CurrentKeys)
        # Ищем запись глазами своего потока — кроме случая «снять у всех»: тот, кто учёл находку
        # персонально, первым и понимает, что тема исчерпана, а его собственное закрытие прячет её
        # от него самого. Без этого исключения единственный выход с доски был бы заперт перед ним.
        $lookupKeys = if ($ForAll) { @() } else { $mineKeys }
        $record = @(
            Select-OpenEntries -Entries $entries -Viewer $lookupKeys |
                Where-Object { [string]$_.Record.id -eq $Id } |
                ForEach-Object { $_.Record }
        )[0]
        if (-not $record) {
            # Отвечаем тем, что есть на самом деле. Общий ответ «закрыли у всех или просрочена» врал
            # чаще всего именно тому, кто минуту назад закрыл запись у себя: ни того, ни другого не
            # случилось, а выход (снять у всех) остался неназванным.
            $states = Get-BoardStates -Entries $entries -Viewer $mineKeys
            $isMine = @($states.ClosedForViewer | Where-Object { [string]$_.Record.id -eq $Id }).Count -gt 0
            $isStale = @($states.Stale | Where-Object { [string]$_.Record.id -eq $Id }).Count -gt 0
            $isBroken = @($states.Broken | Where-Object { [string]$_.Record.id -eq $Id }).Count -gt 0
            if ($isMine) {
                "Запись «$Id» вы уже закрыли у себя — соседям она по-прежнему видна."
                "Тема исчерпана и им не нужна — снять у всех: pwsh scripts/wave-board.ps1 -Mode Done -Id $Id -ForAll"
            } elseif ($isStale) {
                "Запись «$Id» просрочена (старше $(Get-BroadcastLifetimeDays) дней) — она уже сошла с доски."
            } elseif ($isBroken) {
                "У записи «$Id» испорчено поле времени — она снята с доставки; поправьте дату в файле доски."
            } else {
                "Записи «$Id» среди открытых нет — её закрыли у всех либо такой метки на доске не было."
            }
            return
        }
        # ‼️ Закрыть находку с ИМЕННЫМ адресом может только тот, кому она адресована. Такое
        # закрытие ОБЩЕЕ — кто закрыл первым, погасил её у всех, — и потому чужая рука здесь стоит
        # находки целиком: истинный адресат не увидит её ни в доставке, ни на доске, сдастся
        # зелёным с пустым ящиком, а автору придёт «учтено» от потока, которого он не называл.
        #
        # Сегодня доставка носит такую находку ровно одному потоку, так что чужой её метки просто
        # неоткуда узнать. Но проверка стоит второй дверью: узнают — не закроют, а услышат, чья
        # это запись. Осознанный выход остаётся ключом -ForAll: тема исчерпана и адресату не нужна.
        $addressedToMe = $ForAll -or (Get-StreamKey -Raw ([string]$record.to)) -in @('*', '**')
        if (-not $addressedToMe) {
            $registryNow = @(Get-Claims -Dir $registry -Strict)
            Set-KnownWaves -Keys @($registryNow | ForEach-Object { $_.WaveKey })
            $myClaim = Get-CurrentClaim -Dir $registry -Strict
            $myNames = @(Get-StreamNames -Claim $myClaim -Claims $registryNow)
            $addressedToMe = @(Select-ForStream -Records @($record) -Keys $myNames -Claim $myClaim).Count -gt 0
        }
        if (-not $addressedToMe) {
            Deny-Call @"
запись «$Id» адресована не вам, а потоку «$($record.to)» — закрытие такой записи ОБЩЕЕ, и вы погасили бы её у него.
Он её тогда не увидит ни в доставке, ни на доске, а её автору придёт «учтено» от вас.
Тема исчерпана и адресату не нужна — снять у всех осознанно: pwsh scripts/wave-board.ps1 -Mode Done -Id $Id -ForAll
"@
        }
        $closing = [ordered]@{ id = $Id; at = (Get-Date).ToString('s'); done = $true }
        # Широковещательных адресов ДВА: «всем своей волны» и «всем вкладкам проекта». Забыть
        # второй — значит погасить запись у всех разом первым же учтившим её потоком.
        $broadcast = (Get-StreamKey -Raw ([string]$record.to)) -in @('*', '**')
        # Находку «всем» каждый адресат учитывает сам за себя, поэтому её закрытие несёт ключ
        # закрывшего и гасит запись только у него. Общий выход тоже нужен: без него запись не убрать
        # с доски вовсе — она будет приходить каждому НОВОМУ дереву, даже не из этой волны.
        if ($broadcast -and -not $ForAll) {
            if ($mineKeys.Count -eq 0) {
                Deny-Call 'не удалось определить, чей это поток, а закрытие записи «всем» — именное; снять её у всех сразу: -ForAll'
            }
            $closing.by = $mineKeys[0]
        }
        Add-BoardLine -Path $board -Line ($closing | ConvertTo-Json -Depth 2 -Compress)
        # Автору находки говорим, что её учли. Без этого он не узнаёт её судьбу никогда, а от неё
        # зависит, заводить ли ей задание в «Хвостах волны». Уведомление адресовано автору, помечено
        # особым видом и закрывается само при показе — новой работы оно не создаёт.
        # Записи «всем» не подтверждаем: у неё адресатов много, и автор получил бы столько же
        # уведомлений об одном и том же. Подтверждение имеет смысл там, где адресат один и исход
        # у находки определённый.
        $author = Get-StreamKey -Raw ([string]$record.from)
        if ($author -and -not $broadcast -and $author -notin $mineKeys -and [string]$record.kind -ne 'ack') {
            $ack = [ordered]@{
                id    = [guid]::NewGuid().ToString('N').Substring(0, 8)
                at    = (Get-Date).ToString('s')
                wave  = [string]$record.wave
                to    = [string]$record.from
                title = "учтено: «$($record.title)»"
                where = "закрыл поток $(if ($mineKeys.Count -gt 0) { $mineKeys[0] } else { 'неизвестный' })"
                from  = if ($mineKeys.Count -gt 0) { $mineKeys[0] } else { '' }
                kind  = 'ack'
            }
            Add-BoardLine -Path $board -Line ($ack | ConvertTo-Json -Depth 3 -Compress)
        }
        if ($broadcast -and $ForAll) {
            "Запись «$Id» закрыта для всех адресатов — тема исчерпана, соседям она больше не придёт."
        } elseif ($broadcast) {
            "Запись «$Id» закрыта для потока «$($mineKeys[0])» — остальным адресатам она по-прежнему видна."
            "Тема исчерпана и соседям не нужна — снять у всех: pwsh scripts/wave-board.ps1 -Mode Done -Id $Id -ForAll"
        } else {
            "Запись «$Id» закрыта — больше вкладкам не показывается."
        }
    }

    'Compact' {
        $result = Compress-Board -Path $board
        if ($result.Before -eq 0) {
            "Уплотнять нечего — на доске нет ни строки ($board)."
            return
        }
        "Доска уплотнена: было строк $($result.Before), осталось $($result.After) (только открытые записи)."
        if ($result.Unreadable -gt 0) {
            # Обрывок записи — это чья-то находка, которую не разобрать. Стёртое молча неотличимо
            # от того, чего не было, поэтому о выброшенном говорим вслух.
            "Не разобрано и выброшено строк: $($result.Unreadable) — это обрывки записей."
        }
    }

    'Show' {
        $content = Read-BoardContent -Path $board
        if (-not $content.Ok) {
            Deny-Call "доску не удалось прочитать ($board). Последняя причина: $($content.Reason)"
        }
        $entries = Get-BoardEntries -Lines $content.Lines
        # Смотрим глазами названного потока: у него могут быть свои закрытия. Ключей у потока два —
        # по ветке и по папке, и они могут свестись к РАЗНЫМ; берём оба, иначе показ не узнает
        # собственное закрытие этого потока и покажет учтённую находку как открытую.
        $viewer = if ($To) { @(Get-StreamKeys -Raw $To) } else { @() }
        $states = Get-BoardStates -Entries $entries -Viewer $viewer
        $open = Select-Asked -Records @($states.Open | ForEach-Object { $_.Record })
        $closedHere = Select-Asked -Records @($states.ClosedForViewer | ForEach-Object { $_.Record })
        $stale = Select-Asked -Records @($states.Stale | ForEach-Object { $_.Record })
        $broken = Select-Asked -Records @($states.Broken | ForEach-Object { $_.Record })
        $total = $content.Lines.Count
        # Сколько строк уберёт уплотнение, считаем ТЕМ ЖЕ отбором, каким оно и работает: советовать
        # уплотнение, которое ничего не уберёт, — работа впустую и ложная надежда.
        $droppable = $total - @(Select-KeepEntries -Entries $entries).Count
        if ($total -gt $CrowdedLines) {
            "Доска разрослась: строк $total, из них открытых $($open.Count)."
            if ($droppable -gt 0) {
                "Уплотнение уберёт строк: $droppable — pwsh scripts/wave-board.ps1 -Mode Compact"
            } else {
                'Уплотнение ничего не уберёт — на доске только нужные строки.'
            }
            ''
        }
        # Про остальные состояния говорим вслух: молчание о них выглядит как пропажа записи.
        $aside = @()
        if ($closedHere.Count -gt 0) { $aside += "закрыто у вас — $($closedHere.Count)" }
        if ($stale.Count -gt 0) {
            $aside += "просрочено (старше $(Get-BroadcastLifetimeDays) дней) — $($stale.Count)"
        }
        $asideLine = if ($aside.Count -gt 0) { "Ещё на доске: $($aside -join ', ')." } else { $null }
        # Испорченная дата — отдельной строкой: это не «устарело само», а испорченный файл, и
        # человеку надо понять, почему находка пропала и что с ней делать.
        $brokenLine = if ($broken.Count -gt 0) {
            "Записей с испорченным полем времени: $($broken.Count) — они не доставляются; поправьте дату в файле доски или закройте их."
        } else { $null }
        if ($open.Count -eq 0) {
            "Открытых записей на доске волны нет ($board)."
            if ($asideLine) { $asideLine }
            if ($brokenLine) { $brokenLine }
            return
        }
        "Открытых записей на доске волны: $($open.Count) ($board)"
        $anyBroadcast = $false
        foreach ($record in $open) {
            $tail = if ($record.where) { " — $($record.where)" } else { '' }
            $wave = if ($record.wave) { "волна $($record.wave), " } else { '' }
            # Кто уже учёл — только про записи «всем»: у них закрытие персональное, и молчать об
            # этом значит выдавать «ещё никем не учтено» за правду.
            $seen = $states.Closings.By[[string]$record.id]
            $mark = if ($seen -and $seen.Count -gt 0) { " (учли: $($seen -join ', '))" } else { '' }
            if ((Get-StreamKey -Raw ([string]$record.to)) -eq '*') { $anyBroadcast = $true }
            "  [$($record.id)] ${wave}кому: $($record.to) — «$($record.title)»$tail$mark"
        }
        if ($asideLine) { $asideLine }
        if ($brokenLine) { $brokenLine }
        ''
        'Учли находку — закройте её: pwsh scripts/wave-board.ps1 -Mode Done -Id <метка>'
        if ($anyBroadcast) {
            'Запись «всем» гасится только у вас; тема исчерпана и соседям не нужна — добавьте -ForAll.'
        }
    }
}
