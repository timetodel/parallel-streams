#Requires -Version 7
<#
Доска волны: находка, адресованная соседней вкладке, кладётся сюда и доходит до неё сама.

Зачем. План волны вкладка читает ОДИН раз, на старте, и больше не перечитывает; лежит он вдобавок
в её собственном рабочем дереве, где остаётся той версии, что была при старте. Поэтому дописка в
план до живого соседа не доходит вовсе — ни через план, ни через слияние. 20.08.2026 так потерялись
три находки: их адресовали потоку, чья вкладка в этот момент работала по плану недельной давности.

Доска дописку доставляет, но плана не заменяет: находка по-прежнему пишется в план (его читают
следующие вкладки), а на доску кладётся, только пока вкладка соседа ЖИВА.

Адрес потока — его номер в плане волны (`wave6/3`), а не имя ветки: имена врут. В плане волны 6 у
двух потоков объявлена одна ветка, а вкладки работают на других; одну папку вкладка успела занять
под другую работу. Имя ветки и папки принимается по-прежнему — как запасной путь.

Режимы:
  Claim   — объявиться на старте: [-Wave <волна>] [-Stream <номер>] [-StreamName …] [-Tasks …]
            [-Plan …] [-TakeOver]. Волна не названа — берётся из имени плана, из идущей рядом
            работы или по сегодняшней дате; номер потока не назван — выдаётся следующий свободный в
            волне. `-TakeOver` забирает названный адрес у другой рабочей папки (переезд в своё
            дерево, перехват брошенной вкладки).
  Release — сдать поток перед закрытием вкладки (не пройдёт, пока в ящике осталось открытое).
            С `-Wave <волна> -Stream <номер>` сдаёт СИРОТУ по адресу — запись, чьей рабочей папки
            на диске больше нет: папка на месте (пусть даже молчит пятые сутки) — отказ.
  Streams — кто какой поток ведёт: [-Wave …] [-Task <номер задачи>]
  Add     — положить находку:  -To <волна/поток, ветка или папка> -Title <одна строка> [-Where …]
  Show    — показать открытые записи
  Done    — закрыть учтённую находку: -Id <метка>; адресованную всем — только для своего
            потока, а -ForAll снимает её у всех сразу
  Compact — уплотнить доску: оставить только открытые записи
  Path    — напечатать путь к доске

Устройство доски и реестра заявок — в `lib/wave-board-lib.ps1`.
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [ValidateSet('Add', 'Show', 'Done', 'Compact', 'Path', 'Claim', 'Release', 'Streams')]
    [string]$Mode,

    # Кому: номер потока в волне (`wave6/3`), имя ветки потока (`feat/wave3-plan-clock`), имя его
    # рабочей папки, `*` — всем потокам своей волны или `**` — всем вкладкам проекта.
    [string]$To,

    # Положить находку по имени ветки или папки, которой на машине нет вовсе. Адресу вида
    # «волна/поток» ключ не нужен: поток, который ещё не объявлялся, — обычное дело, запись его
    # дождётся.
    [switch]$AllowUnknownStream,

    [string]$Title,

    # Где полный текст: раздел плана, номер задачи, номер заявки. Заголовок на доске — только крючок.
    [string]$Where,

    # ‼️ В сдаче пара `-Wave` и `-Stream` значит другое: сдать СИРОТУ по адресу — запись, чьей
    # рабочей папки на диске больше нет. Свой поток сдаётся из своей папки и ключей не требует.
    [string]$Wave,

    # Номер потока в таблице плана волны: `3`, `П3`, `3b`.
    [string]$Stream,

    # Человеческое имя потока из плана — чтобы соседи узнавали его не по номеру.
    #
    # ‼️ Именно `-StreamName`, а не `-Name`: под коротким именем значение параметра приезжало на
    # сборочный бокс подменённым — вместо переданного имени в заявке оказывалось имя переменной
    # окружения (`GIT_ALTERNATE_OBJECT_DIRECTORIES`), причём одинаково для любых значений, и
    # русских, и латинских. На машине разработки то же самое проходило верно. Соседние параметры
    # (`-Wave`, `-Stream`, `-Tasks`) не страдали — то есть дело в самом имени `-Name`. Обратно не
    # переименовывать.
    [string]$StreamName,

    # Номера задач плана, которые ведёт поток: `10-13` или `10, 11, 12`. По ним видно, чей кусок
    # работы, когда вкладку тянет взять соседнюю задачу.
    [string]$Tasks,

    # Файл плана волны: из его имени берётся волна, если её не назвали отдельно.
    [string]$Plan,

    # Номер задачи для вопроса «чей это кусок» в режиме Streams.
    [string]$Task,

    [string]$Id,

    # Снять запись «всем» у ВСЕХ адресатов сразу: тема исчерпана, дальше она никому не нужна. Без
    # этого ключа закрытие такой записи персональное — гасит её только у закрывшего потока.
    [switch]$ForAll,

    # Сдать поток, не разобрав ящик: то, что в нём осталось, названо в отчёте и переходит в
    # «Хвосты волны» руками. Без ключа сдача не проходит.
    #
    # ‼️ Смысл у ключа РОВНО ОДИН, и второго ему давать нельзя. В соседней копии тем же ключом
    # затирают чужую заявку при объявлении — а раз инструмент сам советует его для сдачи, нажимают
    # его не глядя, и поток из занятой папки исчезает молча. В объявлении ключа принуждения нет
    # вовсе: сдача прежнего потока лежит в той же самой папке, ничего не теряет и даёт тот же исход.
    [switch]$Force,

    # Забрать адрес потока у другой рабочей папки: вкладка переехала в своё дерево (или
    # перехватывает брошенную) и объявляется тем же адресом оттуда.
    #
    # ‼️ Ключ пишет поле преемства в СВОЮ заявку. Чужой файл не трогается ни байтом: у него есть
    # второй писатель — сторож доставки той папки, — и любая пометка в нём стёрлась бы его
    # ближайшей отметкой живости уже после того, как нам отрапортовали об успехе. Адрес гасится
    # вторым проходом загрузчика реестра, а не правкой чужой заявки.
    #
    # ‼️ Смысл у ключа ровно один — перенос адреса. Затирания чужой заявки в объявлении нет вовсе, и
    # заводить его нельзя: сдача прежнего потока лежит в той же самой папке, ничего не теряет и даёт
    # тот же исход.
    [switch]$TakeOver,

    # Только для тестов: доска в стороне от рабочей. В работе не задаётся — путь берётся у git.
    [string]$BoardPath
)

