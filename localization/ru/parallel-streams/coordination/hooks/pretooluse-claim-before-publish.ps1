#Requires -Version 7
<#
Хук PreToolUse: работу вот-вот зафиксируют из потока, который не объявился, — отказать до того, как
она уедет.

Зачем. Объявление — это то, что вообще делает вкладку достижимой: находке соседа есть куда прийти,
задачи потока видны занятыми, а на вопрос «чей это кусок» приходит ответ. Всё остальное в наборе —
уговор, который вкладка соблюдает добровольно; необъявившаяся вкладка — ровно та, которая его не
соблюдает. И напомнить ей нельзя: снаружи её нет, напоминание некуда слать.

Поэтому напоминание ждёт единственного момента, когда необъявленный поток перестаёт быть личным
делом вкладки, — фиксации изменений. До неё работа местная и обратимая; с неё она уезжает в ветку,
в заявку на слияние и в чужой день.

Сторож ОТКАЗЫВАЕТ, а не подсказывает, и это единственное место в наборе, где вкладке в чём-то
отказывают. Довод: подсказку в контексте читает та же вкладка, которая уже пропустила объявление в
своём задании, а отказ останавливает конкретную команду и возвращает строку, которой это лечится.
Он ловит забывчивость, а не умысел, — одна осознанная строка в оболочке его обходит, — и этого
достаточно: на деле случается именно забывчивость.

Выход всегда один и печатается целиком. Соображать не приходится: без волны и без плана канал сам
даёт волну и выдаёт свободный номер.

Осознанное исключение: PARALLEL_STREAMS_ALLOW_UNCLAIMED=1 на сессию. Клапан нужен для случаев,
которые сторож от потока не отличит, — человек фиксирует правку из главной папки, чинит сам канал,
делает разовую рутину. Это одна переменная, и она названа в самом отказе.

При ЛЮБОЙ неожиданности сторож уходит с дороги и выходит нулём: испорченный реестр, нечитаемая
заявка, git не ответил. Набор, который ставят в чужой проект, не вправе превращать свою беду в
проект, где нельзя зафиксировать работу.
#>

param(
    # Только для проверок: доска в стороне от настоящей, ровно как в хуке доставки. В работе путь
    # берётся из git.
    [string]$BoardPath
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

# Команды, после которых работа перестаёт быть личным делом этой вкладки. Фиксация — тот самый
# момент, ради которого сторож заведён; отправка в общий репозиторий и заведение заявки на слияние
# стоят здесь потому, что вкладка могла зафиксировать правку ещё до установки канала, и следующий
# шанс поймать её — этот.
#
# Слияние и перебазирование сюда намеренно НЕ входят: они двигают уже существующую работу, а поток,
# дошедший до слияния, свой шанс быть пойманным давно получил. Отказ там добавил бы отказов в конце
# работы, где они никому не помогают.
$PublishingCommands = '(?i)(\bgit\b[^\r\n]*\b(commit|push)\b|\bgh\b\s+pr\s+create\b)'

function Send-Denial {
    param([string]$Reason)
    @{
        hookSpecificOutput = @{
            hookEventName            = 'PreToolUse'
            permissionDecision       = 'deny'
            permissionDecisionReason = $Reason
        }
    } | ConvertTo-Json -Depth 5 -Compress
    exit 0
}

try {
    . (Join-Path $PSScriptRoot '../lib/hook-io.ps1')
    $raw = Read-HookInput
    if (-not $raw) { exit 0 }
    $call = $raw | ConvertFrom-Json
    if (-not $call) { exit 0 }

    # Команду смотрим ДО того, как что-либо загружено: хук идёт перед каждым вызовом оболочки в
    # сессии, и на чужих ему вызовах он не должен стоить ничего вовсе.
    $command = [string]$call.tool_input.command
    if (-not $command) { exit 0 }
    if ($command -notmatch $PublishingCommands) { exit 0 }

    if ($env:PARALLEL_STREAMS_ALLOW_UNCLAIMED -eq '1') { exit 0 }

    # Рабочую папку берём из вызова, а не оттуда, где случилось запуститься самому хуку: вся
    # личность потока выводится из его рабочего дерева, и вопрос про чужую папку дал бы ответ про
    # чужой поток.
    $cwd = [string]$call.cwd
    if ($cwd -and (Test-Path -LiteralPath $cwd -PathType Container)) {
        Set-Location -LiteralPath $cwd
    }

    . (Join-Path $PSScriptRoot '../lib/wave-board-lib.ps1')

    # ‼️ Спрашиваем СТРОГО, и в этом вся разница между сторожем и помехой. Везде в наборе терпимое
    # чтение стоит одной невидимой строки; здесь оно стоит отказа. При терпимом чтении нечитаемый
    # реестр — отпавший диск, занятый на мгновение файл заявки, папка, подменённая файлом, — вернётся
    # ПУСТЫМ, а пустота неотличима от «поток не объявлялся»: сторож отказал бы вкладке, объявившейся
    # безупречно, и отказывал бы всё время, пока длится беда. Строгий режим превращает каждый такой
    # случай в исключение, а перехват ниже — исключение в молчание.
    $registry = Get-RegistryDir -BoardOverride $BoardPath

    # ‼️ Вид самого реестра проверяем отдельно, до чтения, — потому что одной строгости мало: на
    # разных системах ответ разный. ФАЙЛ, лежащий на месте папки заявок, даёт на Windows один сбой
    # (строгое чтение отказывает вслух), а на Linux — другой, неотличимый от «папки ещё нет»: там
    # строгое чтение возвращает пустой список и никакой ошибки. На таком ответе сторож отказал бы в
    # каждой фиксации в проекте, и отказ был бы неверным. Вопрос «что физически лежит по этому пути»
    # решает дело одинаково везде.
    #
    # «Нет ничего» сюда НЕ входит: пустой реестр значит, что никто ещё не объявлялся, — в том числе
    # первый поток волны, ради которого сторож и заведён.
    $registryState = Get-PathState -Path $registry
    if ($registryState.Kind -eq 'leaf' -or $registryState.Kind -eq 'unknown') { exit 0 }

    $claims = @(Get-Claims -Dir $registry -Strict)
    $claim = Get-CurrentClaim -Dir $registry -Strict
    if (-not $claim) {
        # Второй путь к СВОЕЙ заявке — тот же, которым уже ходят доставка и сдача: ТОЧНОЕ совпадение
        # с папкой рабочего дерева, записанной в заявке. Заявки, поданные прежней версией из
        # подкаталога дерева, лежат под ключом того подкаталога, и каноническим ключом (корнем
        # дерева) их не найти. Без этого пути сторож отказал бы вкладке, объявившейся безупречно.
        $found = Find-ClaimByWorktree -Claims $claims -Paths @((Get-TreeRoot), $PWD.Path)
        if ($found) { $claim = $found.Record }
    }

    # ‼️ Открытость спрашиваем единым признаком закрытости, а не чтением поля состояния: заявка,
    # адрес которой перехвачен другой папкой, в своём файле по-прежнему выглядит открытой, а вкладка,
    # которая её держит, снаружи недостижима ни для кого.
    if ($claim -and -not (Test-ClaimClosed -Claims $claims -Claim $claim)) { exit 0 }

    $announce = 'pwsh scripts/wave-board.ps1 -Mode Claim -Wave <волна> -Stream <номер> -StreamName "<имя>" -Tasks "<задачи>"'
    $valve = 'Это не поток (фиксация из главной папки, починка самого канала, разовая рутина) — осознанное исключение: переменная окружения PARALLEL_STREAMS_ALLOW_UNCLAIMED=1 на эту сессию.'

    if ($claim) {
        # Поток закрыт: сдан или его адрес перехвачен в другую папку. Снаружи это одно и то же —
        # адрес никто не ведёт, находку для него на приёме отклоняют, а задачи снова числятся
        # ничьими.
        $address = "$($claim.wave)/$($claim.stream)"
        Send-Denial (@(
                "Остановлено перед фиксацией: поток $address из этой папки больше не ведётся — он сдан либо его адрес переехал в другое рабочее дерево."
                ''
                'Снаружи этой вкладки нет: адрес никто не ведёт, находку для него на приёме отклоняют, а задачи, которые тут делались, числятся ничьими.'
                ''
                'Объявитесь заново — верните адрес себе или возьмите свободный номер:'
                "  pwsh scripts/wave-board.ps1 -Mode Claim -Wave $($claim.wave) -Stream $($claim.stream) -TakeOver"
                '  pwsh scripts/wave-board.ps1 -Mode Claim'
                ''
                $valve
            ) -join "`n")
    }

    Send-Denial (@(
            'Остановлено перед фиксацией: этот поток не объявлялся на канале координации.'
            ''
            'За пределами этой папки о вкладке никто не знает. Соседу некуда прислать находку, задачи, которые тут делаются, числятся ничьими, а на вопрос соседа «чей это кусок» приходит ответ «ничей» — и кусок предлагают владельцу, который не может знать, что он был запланирован этому потоку.'
            ''
            'Объявите поток и повторите команду:'
            "  $announce"
            ''
            'Волну и номер берут из таблицы плана. В проекте нет ни волн, ни плана — не передавайте ничего вовсе, канал сам даст волну и выдаст свободный номер:'
            '  pwsh scripts/wave-board.ps1 -Mode Claim'
            ''
            $valve
        ) -join "`n")
} catch {
    exit 0
}
