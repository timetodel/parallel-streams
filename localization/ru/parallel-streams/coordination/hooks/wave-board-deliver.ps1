#Requires -Version 7
# ПЕРЕХОДНОЕ: имя, под которым хук доставки жил до 1.19.0, — сам хук теперь `deliver-wave-board.ps1`,
# рядом с этим файлом. Убрать не раньше следующей мажорной версии: до неё настройки, записанные до
# 1.19.0, ещё могут звать это имя.
#
# Зачем он. До 1.19.0 обновление описывалось как «скопировать новую папку поверх старой», без запуска
# установщика, а копирование ничего не удаляет: настройки, записанные прежним установщиком, либо не
# нашли бы здесь ничего (хук молча выключен), либо продолжали бы запускать устаревший скрипт с новой
# библиотекой. Повторный запуск установщика переписывает их на новое имя.
#
# Передаёт вызов целиком — аргументы, стандартный ввод (здесь его не читают: его читает хук), вывод,
# код выхода. Код передаётся только при неудачном вызове: хук, закончившийся без `exit`, оставляет
# после себя код последнего вызова git, и передать его — значит превратить успех в сбой.
& (Join-Path $PSScriptRoot 'deliver-wave-board.ps1') @args
if (-not $?) { exit $LASTEXITCODE }
